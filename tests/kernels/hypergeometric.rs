/// `M(a, b, z)` summed exactly in rational arithmetic (the arguments are
/// multiples of 1/2): an independent high-precision reference.
fn exact_m(
    a: (i64, i64),
    b: (i64, i64),
    z: (i64, i64),
) -> f64 {
    use num_bigint::BigInt;
    use num_rational::BigRational;
    use num_traits::Signed;
    use num_traits::ToPrimitive;
    use num_traits::Zero;
    let r = |p: (i64, i64)| BigRational::new(BigInt::from(p.0), BigInt::from(p.1));
    let (a, b, z) = (r(a), r(b), r(z));
    let mut term = BigRational::from_integer(BigInt::from(1));
    let mut sum = term.clone();
    let mut k = 0_i64;
    loop {
        let kk = BigRational::from_integer(BigInt::from(k));
        term = term * (&a + &kk) / (&b + &kk) * &z / BigRational::from_integer(BigInt::from(k + 1));
        sum += &term;
        k += 1;
        if k > 20
            && !sum.is_zero()
            && (term.abs() * BigRational::from_integer(BigInt::from(10).pow(30)) < sum.abs())
        {
            break;
        }
        assert!(k < 40_000, "the reference series did not converge");
    }
    sum.to_f64().unwrap()
}

