#[test]
fn kummer_m_with_complex_large_parameters_matches_mpmath() {
    let table = [
        (
            (c(60.5, 5.0), c(90.5, -3.0), c(20.0, 30.0)),
            c(-19252.158982494149, -38494.08001012119),
        ),
        (
            (c(120.5, 0.0), c(80.5, 0.0), c(30.0, 0.0)),
            c(1.818573545874163e18, 0.0),
        ),
        (
            (c(120.5, 0.0), c(80.5, 0.0), c(-30.0, 0.0)),
            c(6.2782401208721933e-25, 0.0),
        ),
        (
            (c(40.5, 10.0), c(70.5, 2.0), c(-25.0, 15.0)),
            c(-1.0106578950458413e-7, -1.2934471035869015e-7),
        ),
        (
            (c(-50.5, 0.0), c(30.5, 0.0), c(40.0, 0.0)),
            c(7.8962657378415613e-12, 0.0),
        ),
        (
            (c(100.5, 20.0), c(60.5, -10.0), c(-40.0, -30.0)),
            c(-1.335743848303659e-12, -2.4985086066868333e-12),
        ),
        (
            (c(30.5, 0.0), c(200.5, 0.0), c(400.0, 0.0)),
            c(7.0240253893566796e66, 0.0),
        ),
    ];
    for ((a, b, z), want) in table {
        close(
            hyp1f1_cplx(a, b, z),
            want,
            1e-12,
            &format!("M({a}, {b}, {z})"),
        );
    }
    // Kummer's transformation and a contiguous relation at large complex parameters.
    let (a, b) = (c(70.5, 4.0), c(90.5, -2.0));
    for z in [c(15.0, 10.0), c(-20.0, 5.0), c(3.0, -30.0)] {
        let lhs = hyp1f1_cplx(a, b, z);
        let rhs = z.exp() * hyp1f1_cplx(b - a, b, -z);
        close(
            lhs,
            rhs,
            1e-11,
            &format!("M(a, b, z) = e^z M(b - a, b, -z) at {z}"),
        );
        // b (b-1) M(a, b-1) + b (1-b-z) M(a, b) + z (b-a) M(a, b+1) = 0
        let one = c(1.0, 0.0);
        let r = b * (b - one) * hyp1f1_cplx(a, b - one, z)
            + b * (one - b - z) * hyp1f1_cplx(a, b, z)
            + z * (b - a) * hyp1f1_cplx(a, b + one, z);
        let scale = (b * (one - b - z) * lhs).norm();
        assert!(
            r.norm() < 1e-10 * scale,
            "contiguous relation at {z}: {:e}",
            r.norm() / scale
        );
    }
}

