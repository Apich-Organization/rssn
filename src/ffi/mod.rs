//! # C interface
//!
//! A deliberately small C ABI over [`crate::api`]. Every entry point is
//! `extern "C"`, never unwinds (panics become [`RssnStatus::Panic`]) and
//! reports failures through a status code plus a thread-local message
//! readable with [`rssn_last_error`].
//!
//! Ownership rules:
//! * `rssn_session_new` / `rssn_config_new` return heap objects that must
//!   be released with `rssn_session_free` / `rssn_config_free`.
//! * Terms are `uint32_t` handles valid for the session that made them;
//!   [`RSSN_NO_TERM`] signals failure.
//! * Strings returned by rssn are owned by the caller and must be released
//!   with `rssn_string_free`; byte buffers with [`rssn_bytes_free`]; tensors
//!   with `rssn_tensor_free`.
//!
//! The header `rssn.h` is generated by cbindgen (`DEV=1 cargo build --features dev-headers`).
//!
//! # Limitations and coverage
//!
//! The ABI is deliberately narrow; in priority order, what it does not do:
//!
//! 1. **It is a JSON-and-handles ABI, not a typed ABI.** Answers cross as
//!    JSON text (`rssn_compute_json`, `rssn_dimension`, `rssn_sim_run`,
//!    `rssn_manifest_json`) or as the two plain C structs [`RssnAnswer`] and
//!    [`RssnTensor`]. Terms are `uint32_t` handles into one session, never
//!    pointers to Rust objects. There are no per-operator entry points
//!    (`rssn_diff`, `rssn_integral`, ...) and no way to pass a dynamic
//!    [`Value`](crate::kernel::value::Value) across: a host that needs the
//!    value ABI uses [`Session::call_value`](crate::api::Session::call_value)
//!    from Rust, or the kernel plugin ABI, which exchanges `bincode-next`
//!    buffers. A host that needs an operator by name builds the request with
//!    `rssn_term_apply` and computes it.
//! 2. **Two binary wire formats: single and batch compute.**
//!    [`rssn_compute_bincode`] carries the same record as the JSON path (see
//!    [`RssnComputeRecord`]) in the deterministic `bincode-next` encoding of
//!    [`crate::kernel::codec::encode_deterministic`] — the format plugin ABI
//!    messages are sent in and content-address digests are computed over; the
//!    bytes are opaque to C and are released with [`rssn_bytes_free`].
//!    [`rssn_compute_all_bincode`] is the batch counterpart: one
//!    [`RssnBatchEntry`] per input handle, in input order, each holding the
//!    request's [`RssnStatus`] as its numeric value plus the answer record when
//!    it succeeded, so a partially failing batch still crosses in one buffer.
//!    Configuration, terms and tensors have no bincode form — those stay
//!    handles and C structs.
//!
//!    The bytes are **not self-framing**: `*out_len` is the exact length and
//!    nothing marks the end of the value, so a payload cut at a sequence
//!    boundary can decode as a shorter batch instead of failing. A host must
//!    treat the length as authoritative and, for untrusted storage, also check
//!    a digest ([`crate::kernel::codec::digest`]) rather than relying on the
//!    decoder to reject truncation.
//! 3. **`RssnStatus` is the whole error vocabulary, and it is coarse.** Every
//!    [`ComputeError`] variant maps to one code (`Rule`, `Parse`,
//!    `UnknownOperator`, `NotNumeric`, `Dimension`, `Inconsistent`) as do the
//!    boundary errors (`NullArgument`, `InvalidUtf8`, `NoSuchTerm`, `NoValue`,
//!    `InvalidArgument`, `Simulation`, `Panic`). The message is for humans
//!    only: rssn makes no promise about its wording, so a host branches on
//!    the code and never parses the string. Dimension detail is not in the
//!    status: in strict mode a conflict is `Dimension`, while advisory
//!    findings and the names of conflicting dimensions are only in the JSON
//!    `diagnostics` array (or the bincode record). The stable *codes* of those
//!    findings are exposed separately, per thread, by
//!    [`rssn_dimension_count`] and [`rssn_dimension_code`] — the
//!    [`DimError::code`](crate::graph::DimError::code) strings (`mismatch`,
//!    `unknown_unit`, `unannotated`, ...) — for the most recent computation on
//!    the thread, so a host branches on them without parsing a message.
//! 4. **`rssn_last_error` semantics.** The message is thread-local, is set by
//!    the call that failed and is *not* cleared by a later successful call.
//!    Read it immediately after a failure; the pointer is valid only until
//!    the next failing rssn call on the same thread, and must not be freed.
//!    [`rssn_compute_all`] and [`rssn_compute_all_bincode`] are the calls that
//!    can fail per request while returning `Ok`: each entry's code is exact,
//!    and the message of the first failing request is left here (if the
//!    failure was a computation; a handle that does not resolve leaves its own
//!    message).
//! 5. **Shortcut entry points have no status.** `rssn_simplify`, the four
//!    `rssn_term_to_*` renderers and the term constructors report failure as
//!    `RSSN_NO_TERM`/null with the reason in `rssn_last_error`; the return
//!    value alone does not say *why*.
//! 6. **Null contract.** Pointers are checked before they are dereferenced
//!    where the ABI promises a check: output pointers and caller arrays may be
//!    null and produce `NullArgument`; string arguments must be
//!    NUL-terminated UTF-8 (`NullArgument` / `InvalidUtf8`). Output and array
//!    pointers are validated before handles are resolved. A non-null session
//!    pointer must be live for the whole call.
//! 7. **Session and handle lifetime.** A session owns every term made through
//!    it; terms live until `rssn_session_free`. Handles are `uint32_t` indices,
//!    not pointers, and are meaningless in another session or after the
//!    session is freed. There is no generation counter, so a stale handle that
//!    is still in range resolves to that node; a stale *session* pointer is
//!    undefined behaviour. Free each non-null object exactly once; null is
//!    ignored.
//! 8. **Thread-safety.** A session is single-threaded: its store is a
//!    `RefCell`, so two threads using one session concurrently hit a borrow
//!    conflict, which is a panic (a `Panic` status in unwind builds, an abort
//!    in the release profile). Different sessions may be used on different
//!    threads. The shared state is the process-wide unit table and manifest
//!    cache (built once under a lock) and the per-thread `rssn_last_error`.
//!    `rssn_compute_all` parallelises internally on the crate's rayon pool and
//!    its answers do not depend on the thread count.
//! 9. **Panic containment is a build property.** Entry points catch unwinding
//!    panics and report `Panic`, but `[profile.release]` sets
//!    `panic = "abort"`, so a release cdylib aborts the process instead. Do
//!    not make rssn panic in a host that cannot tolerate that.
//! 10. **Header regeneration is a separate build.** `rssn.h` and `rssn.hpp`
//!     are generated by cbindgen from this module and only rewritten by
//!     `DEV=1 cargo build --features dev-headers`; a normal build updates the exported symbols but not
//!     the checked-in headers. The checked-in headers describe every exported
//!     entry point, including the bincode ones, but any *new* entry point must
//!     be followed by a `DEV=1 cargo build --features dev-headers` whose regenerated headers are
//!     committed with the API change.
//! 11. **Tensor data is `f64` and rectangular.** `rssn_term_tensor_data` only
//!     extracts a rectangular list of exact reals as row-major `f64`: a rank-0
//!     scalar has one value, a ragged or non-numeric list is `NoValue`. Sparse
//!     tensors, complex entries and non-numeric containers have no C form;
//!     use the Rust API for those. The caller releases both buffers with
//!     `rssn_tensor_free`.
//! 12. **The C ABI covers the standard build, not plugins.** The manifest
//!     entry points describe the process-wide standard rule sets, not a
//!     session's plugins; a host that needs a per-session manifest reads it
//!     through [`Session::manifest`](crate::api::Session::manifest) in Rust.

