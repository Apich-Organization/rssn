/// The handle value that means "no term" (a failed constructor).
pub const RSSN_NO_TERM: u32 = u32::MAX;

/// Outcome of an rssn C call.
#[repr(C)]
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum RssnStatus {
    /// Success.
    Ok = 0,
    /// A required pointer argument was null.
    NullArgument = 1,
    /// A string argument was not valid UTF-8.
    InvalidUtf8 = 2,
    /// Input text could not be parsed.
    Parse = 3,
    /// An operator name is not registered, or got the wrong arity.
    UnknownOperator = 4,
    /// A numeric answer was requested but none could be determined.
    NotNumeric = 5,
    /// A rule set derived a contradiction; discard the session.
    Inconsistent = 6,
    /// A rule set failed to install.
    Rule = 7,
    /// A term handle does not belong to the session.
    NoSuchTerm = 8,
    /// The term has no value of the requested kind.
    NoValue = 9,
    /// A simulation failed or was given bad parameters.
    Simulation = 10,
    /// rssn panicked; this is a bug.
    Panic = 11,
    /// A dimension conflict in strict mode.
    Dimension = 12,
    /// A scalar argument has an invalid value (for example an unknown
    /// dimension mode).
    InvalidArgument = 13,
}

thread_local! {
    static LAST_ERROR: RefCell<CString> = RefCell::new(CString::default());
}

fn set_error(message: &str) {
    let text = CString::new(message.replace('\0', " ")).unwrap_or_default();
    LAST_ERROR.with(|e| *e.borrow_mut() = text);
}

/// Records `message` and returns `status`.
pub(crate) fn fail(
    status: RssnStatus,
    message: &str,
) -> RssnStatus {
    set_error(message);
    status
}

/// The status code of a computation error.
pub(crate) const fn status_of(e: &ComputeError) -> RssnStatus {
    match e {
        | ComputeError::Rule(_) => RssnStatus::Rule,
        | ComputeError::Parse(_) => RssnStatus::Parse,
        | ComputeError::UnknownOperator(_) => RssnStatus::UnknownOperator,
        | ComputeError::NotNumeric(_) => RssnStatus::NotNumeric,
        | ComputeError::Dimension(_) => RssnStatus::Dimension,
        | ComputeError::Inconsistent(_) => RssnStatus::Inconsistent,
    }
}

pub(crate) fn compute_error(e: &ComputeError) -> RssnStatus {
    fail(status_of(e), &e.to_string())
}

/// Runs `body`, turning a panic into [`RssnStatus::Panic`].
pub(crate) fn guard(body: impl FnOnce() -> RssnStatus) -> RssnStatus {
    catch_unwind(AssertUnwindSafe(body)).unwrap_or_else(|panic| {
        let message = panic
            .downcast_ref::<String>()
            .map(String::as_str)
            .or_else(|| panic.downcast_ref::<&str>().copied())
            .unwrap_or("panic");
        fail(RssnStatus::Panic, message)
    })
}

/// Borrows a C string argument as `&str`.
///
/// # Safety
/// `text` must be null or point to a NUL-terminated string that stays
/// valid for `'a`.
pub(crate) unsafe fn text<'a>(text: *const c_char) -> Result<&'a str, RssnStatus> {
    if text.is_null() {
        return Err(fail(RssnStatus::NullArgument, "null string argument"));
    }
    // SAFETY: non-null and NUL-terminated by the caller's contract.
    unsafe { CStr::from_ptr(text) }
        .to_str()
        .map_err(|_| fail(RssnStatus::InvalidUtf8, "string argument is not UTF-8"))
}

/// Hands a Rust string to C; null if it contains a NUL byte.
pub(crate) fn to_c(text: String) -> *mut c_char {
    CString::new(text).map_or(std::ptr::null_mut(), CString::into_raw)
}

/// The message of the last failed call on this thread (empty if none).
/// The pointer stays valid until the next failing rssn call on this
/// thread; do not free it.
#[unsafe(no_mangle)]
pub extern "C" fn rssn_last_error() -> *const c_char {
    LAST_ERROR.with(|e| e.borrow().as_ptr())
}

thread_local! {
    /// The stable codes of the dimension diagnostics of the most recent
    /// computation on this thread; empty when it reported none.
    static LAST_DIMENSION_CODES: RefCell<Vec<CString>> = const { RefCell::new(Vec::new()) };
}

/// Replaces the recorded dimension codes with `codes`.
pub(crate) fn remember_dimension_codes<'a>(codes: impl IntoIterator<Item = &'a str>) {
    LAST_DIMENSION_CODES.with(|slot| {
        let mut slot = slot.borrow_mut();
        slot.clear();
        for code in codes {
            slot.push(CString::new(code).unwrap_or_default());
        }
    });
}

/// Records the dimension findings of an answer's diagnostics.
pub(crate) fn remember_dimensions(diagnostics: &[crate::graph::DimError]) {
    remember_dimension_codes(diagnostics.iter().map(crate::graph::DimError::code));
}

/// Clears the recorded dimension codes (a computation that found none).
pub(crate) fn clear_dimensions() {
    remember_dimension_codes([]);
}

/// Number of dimension diagnostics reported by the most recent computation on
/// this thread; `0` when it reported none (or when no computation has run).
///
/// A strict-mode conflict is one finding (its code is the conflict kind); an
/// advisory run reports every finding it collected, in answer order. For a
/// batch call the value describes the *last* request in input order, exactly
/// as `rssn_last_error` describes the first *failing* one.
#[unsafe(no_mangle)]
pub extern "C" fn rssn_dimension_count() -> usize {
    LAST_DIMENSION_CODES.with(|slot| slot.borrow().len())
}

/// The stable code of dimension diagnostic `index` of the most recent
/// computation on this thread.
///
/// The code is one of the [`DimError::code`] strings such as `"mismatch"`,
/// `"unknown_unit"` or `"unannotated"`, or null when `index` is out of range.
///
/// The pointer is valid until the next computation on the same thread; it must
/// not be freed. A computation that reports no findings clears the list, so a
/// host reads these immediately after the call it cares about.
///
/// [`DimError::code`]: crate::graph::DimError::code
#[unsafe(no_mangle)]
pub extern "C" fn rssn_dimension_code(index: usize) -> *const c_char {
    LAST_DIMENSION_CODES.with(|slot| {
        slot.borrow()
            .get(index)
            .map_or(std::ptr::null(), |code| code.as_ptr())
    })
}

/// Releases a string returned by rssn. Null is ignored.
///
/// # Safety
/// `text` must be null or a string returned by rssn and not yet freed.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn rssn_string_free(text: *mut c_char) {
    if !text.is_null() {
        // SAFETY: produced by `CString::into_raw` in `to_c`.
        drop(unsafe { CString::from_raw(text) });
    }
}

/// Releases a byte buffer returned by rssn (for example by
/// [`rssn_compute_bincode`]). Null is ignored.
///
/// # Safety
/// `data` must be null or a buffer returned by rssn with this `len`, not yet
/// freed, and not used afterwards.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn rssn_bytes_free(
    data: *mut u8,
    len: usize,
) {
    if !data.is_null() {
        // SAFETY: produced by `Box::into_raw` of a boxed slice of `len` bytes
        // and handed out once.
        drop(unsafe { Box::from_raw(std::ptr::slice_from_raw_parts_mut(data, len)) });
    }
}

/// The crate version, e.g. `"3.0.0-rc.1"`. Static; do not free.
#[unsafe(no_mangle)]
pub const extern "C" fn rssn_version() -> *const c_char {
    concat!(env!("CARGO_PKG_VERSION"), "\0").as_ptr().cast()
}

/// Runs the simulation scenario `name` (see
/// [`crate::sim::scenario::SCENARIOS`]) with JSON parameters and stores
/// the JSON result in `*out` (free with `rssn_string_free`).
///
/// # Safety
/// `name` and `params` must be NUL-terminated strings; `out` must be a
/// valid pointer.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn rssn_sim_run(
    name: *const c_char,
    params: *const c_char,
    out: *mut *mut c_char,
) -> RssnStatus {
    guard(|| {
        if out.is_null() {
            return fail(RssnStatus::NullArgument, "null output pointer");
        }
        // SAFETY: forwarded caller contract.
        let (name, params) = match unsafe { (text(name), text(params)) } {
            | (Ok(n), Ok(p)) => (n, p),
            | (Err(e), _) | (_, Err(e)) => return e,
        };
        match crate::sim::scenario::run(name, params) {
            | Ok(json) => {
                // SAFETY: `out` is non-null and valid by contract.
                unsafe { *out = to_c(json) };
                RssnStatus::Ok
            },
            | Err(e) => fail(RssnStatus::Simulation, &e),
        }
    })
}

