        assert_eq!(s("sc_dimension(sc_complex(list()))"), "-1");
        assert_eq!(s("sc_simplices(sc_complex(list(list(0, 1, 2))), 1)"), "list(list(0, 1), list(0, 2), list(1, 2))");
