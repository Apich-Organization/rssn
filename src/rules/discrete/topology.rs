fn vietoris_rips(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (points, eps, max_dim) = match a {
        | [p, e] => (p, e, 2),
        | [p, e, d] => (p, e, count(cx.graph, *d, MAX_DIM)?),
        | _ => return None,
    };
    let points = read_points(cx.graph, *points)?;
    let eps = radius(cx.graph, *eps)?;
    complex_v(cx.graph, &kt::close_complex(&kt::vietoris_rips_complex(&points, eps, max_dim)))
}

fn vietoris_rips_filtration(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [p, e, s] = a else { return None };
    let points = read_points(cx.graph, *p)?;
    let (eps, steps) = (radius(cx.graph, *e)?, count(cx.graph, *s, MAX_STEPS)?);
    let mut out = Vec::new();
    for (eps, complex) in kt::vietoris_rips_filtration(&points, eps, steps) {
        out.push(V::List(vec![V::Float(eps), complex_v(cx.graph, &complex)?]));
    }
    Some(V::List(out))
}

fn betti_at_radius(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [p, e, d] = a else { return None };
    let points = read_points(cx.graph, *p)?;
    let (eps, dim) = (radius(cx.graph, *e)?, count(cx.graph, *d, MAX_DIM)?);
    Some(V::List(kt::betti_numbers_at_radius(&points, eps, dim).into_iter().map(V::uint).collect()))
}

fn persistence(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [p, e, s, d] = a else { return None };
    let points = read_points(cx.graph, *p)?;
    let eps = radius(cx.graph, *e)?;
    let (steps, dim) = (count(cx.graph, *s, MAX_STEPS)?, count(cx.graph, *d, MAX_DIM)?);
    let diagrams = kt::compute_persistence(&points, eps, steps, dim);
    Some(V::List(
        diagrams
            .into_iter()
            .map(|d| V::List(d.intervals.iter().map(|i| V::List(vec![V::Float(i.birth), V::Float(i.death)])).collect()))
            .collect(),
    ))
}

fn euclidean_distance(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [p, q] = a else { return None };
    let (p, q) = (floats(cx.graph, *p)?, floats(cx.graph, *q)?);
    (p.len() == q.len()).then(|| V::Float(kt::euclidean_distance(&p, &q)))
}

