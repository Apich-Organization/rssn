//! Algebraic topology: simplicial complexes, homology and persistence.
//!
//! A simplicial complex is the inert term `sc(list(simplex, ...))`: each
//! simplex is a sorted `list` of vertex integers, the list is closed under
//! faces and sorted by dimension and then lexicographically. Every operator
//! that reads a complex normalises it first, so any list of simplices may be
//! wrapped in `sc(...)` by hand. A *chain* is `list(list(coeff, simplex),
//! ...)`; the coefficients may be arbitrary terms. Point clouds are lists of
//! coordinate lists.
//!
//! The numeric algorithms live in [`crate::kernels::topology`]; Betti numbers
//! use exact rational ranks of the integer boundary matrices.
//!
//! | operator | value |
//! |---|---|
//! | `sc_complex(list(simplices...))` | the complex generated by the simplices (closed under faces, normalised) |
//! | `sc_dimension(K)` | the dimension (`-1` for the empty complex) |
//! | `sc_simplices(K, k)` | the `k`-simplices |
//! | `sc_simplex_dimension(s)` | `len(s) - 1` |
//! | `sc_euler_characteristic(K)` | `sum (-1)^k #k-simplices` |
//! | `sc_boundary(s)` | the boundary chain `list(list(coeff, face), ...)`, signs `(-1)^i` |
//! | `sc_boundary_matrix(K, k)`, `sc_coboundary_matrix(K, k)` | integer matrix of `d_k` (rows `(k-1)`-simplices, columns `k`-simplices) and of `d^k` (its transpose) |
//! | `sc_chain_boundary(K, chain)` | the boundary of a chain of `k`-simplices of `K`; coefficients simplified, zeros dropped |
//! | `sc_betti(K, k)`, `sc_cohomology_betti(K, k)` | Betti numbers (homology, cohomology) |
//! | `sc_verify_boundary(K)`, `sc_verify_coboundary(K)` | `d d = 0` (resp. `d^ d^ = 0`) |
//! | `sc_components(K)` | connected components of the 1-skeleton, as vertex lists |
//! | `sc_grid(w, h)`, `sc_torus(m, n)` | triangulated grid; triangulated torus (`m, n >= 3`) |
//! | `vietoris_rips(points, eps[, max_dim])` | the Vietoris-Rips complex (`max_dim` defaults to 2) |
//! | `vietoris_rips_filtration(points, max_eps, steps)` | `list(list(eps, K), ...)`, the 1-skeleton at `steps + 1` radii |
//! | `betti_at_radius(points, eps, max_dim)` | `list(b0, ..., b_max_dim)` of the Vietoris-Rips complex |
//! | `persistence(points, max_eps, steps, max_dim)` | per dimension the list of `list(birth, death)` (naive algorithm: Betti numbers tracked over `steps + 1` radii) |
//! | `euclidean_distance(p, q)` | the distance of two points (float) |

