/// Largest point cloud / `max_dim` / step count accepted.
const MAX_POINTS: usize = 300;
const MAX_DIM: usize = 8;
const MAX_STEPS: usize = 2000;

fn simplex_v(s: &[usize]) -> V {
    V::ints(s.iter().map(|&v| v as u64))
}

fn complex_v(
    g: &mut Graph,
    complex: &[Simplex],
) -> Option<V> {
    let list = V::List(complex.iter().map(|s| simplex_v(s)).collect()).build(g);
    apply(g, "sc", &[list]).map(V::Node)
}

fn simplex(
    g: &Graph,
    n: NodeId,
) -> Option<Simplex> {
    idxs(g, n)
}

fn read_simplices(
    g: &Graph,
    n: NodeId,
) -> Option<Vec<Simplex>> {
    items(g, n)?.into_iter().map(|s| simplex(g, s)).collect()
}

/// The complex of an `sc(...)` term, normalised.
fn read_complex(
    g: &Graph,
    node: NodeId,
) -> Option<Vec<Simplex>> {
    let op = g.ops().lookup("sc")?;
    let found = if g.op(node) == op { node } else { g.enodes(g.find(node)).find(|&e| g.op(e) == op)? };
    let [list] = g.children(found) else { return None };
    Some(kt::close_complex(&read_simplices(g, *list)?))
}

fn read_points(
    g: &Graph,
    n: NodeId,
) -> Option<Vec<Vec<f64>>> {
    let points: Vec<Vec<f64>> = items(g, n)?.into_iter().map(|p| floats(g, p)).collect::<Option<_>>()?;
    (points.len() <= MAX_POINTS).then_some(points)
}

fn count(
    g: &Graph,
    n: NodeId,
    limit: usize,
) -> Option<usize> {
    idx(g, n).filter(|&v| v <= limit)
}

fn radius(
    g: &Graph,
    n: NodeId,
) -> Option<f64> {
    float(g, n).filter(|x| x.is_finite() && *x >= 0.0)
}

fn complex_arg(
    cx: &Cx<'_>,
    a: &[NodeId],
) -> Option<Vec<Simplex>> {
    read_complex(cx.graph, *a.first()?)
}

// ----------------------------------------------------------------------
// Complexes and chains
// ----------------------------------------------------------------------

fn sc_complex(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let simplices = read_simplices(cx.graph, *a.first()?)?;
    complex_v(cx.graph, &kt::close_complex(&simplices))
}

fn sc_dimension(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let k = complex_arg(cx, a)?;
    Some(V::int(kt::complex_dimension(&k).map_or(-1, |d| d as i64)))
}

fn sc_simplices(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [k, d] = a else { return None };
    let k = read_complex(cx.graph, *k)?;
    let d = idx(cx.graph, *d)?;
    Some(V::List(kt::simplices_of_dim(&k, d).iter().map(|s| simplex_v(s)).collect()))
}

fn sc_simplex_dimension(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let s = simplex(cx.graph, *a.first()?)?;
    (!s.is_empty()).then(|| V::uint(s.len() - 1))
}

fn sc_euler_characteristic(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    Some(V::int(kt::euler_characteristic(&complex_arg(cx, a)?)))
}

fn sc_boundary(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let s = simplex(cx.graph, *a.first()?)?;
    let mut sorted = s.clone();
    sorted.sort_unstable();
    sorted.dedup();
    if s.is_empty() || sorted.len() != s.len() {
        return None;
    }
    Some(V::List(
        kt::simplex_boundary(&s).into_iter().map(|(c, f)| V::List(vec![V::int(c), simplex_v(&f)])).collect(),
    ))
}

/// The `k`-th boundary matrix of a complex, for `1 <= k <= dim`.
fn boundary_of(
    complex: &[Simplex],
    k: usize,
) -> Option<Vec<Vec<i64>>> {
    if k == 0 {
        return None;
    }
    let cols = kt::simplices_of_dim(complex, k);
    if cols.is_empty() {
        return None;
    }
    Some(kt::boundary_matrix(&kt::simplices_of_dim(complex, k - 1), &cols))
}

fn int_matrix_v(m: &[Vec<i64>]) -> V {
    V::List(m.iter().map(|r| V::ints(r.iter().copied())).collect())
}

fn sc_boundary_matrix(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [k, d] = a else { return None };
    let complex = read_complex(cx.graph, *k)?;
    Some(int_matrix_v(&boundary_of(&complex, idx(cx.graph, *d)?)?))
}

fn sc_coboundary_matrix(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [k, d] = a else { return None };
    let complex = read_complex(cx.graph, *k)?;
    let d = idx(cx.graph, *d)?;
    let m = boundary_of(&complex, d + 1)?;
    let cols = kt::simplices_of_dim(&complex, d + 1).len();
    Some(int_matrix_v(&kt::transpose(&m, cols)))
}

fn sc_chain_boundary(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [k, chain] = a else { return None };
    let complex = read_complex(cx.graph, *k)?;
    let mut terms: Vec<(NodeId, Simplex)> = Vec::new();
    for t in items(cx.graph, *chain)? {
        let [c, s] = items(cx.graph, t)?.as_slice().try_into().ok()?;
        terms.push((c, simplex(cx.graph, s)?));
    }
    let Some((_, first)) = terms.first() else { return Some(V::List(Vec::new())) };
    let dim = first.len().checked_sub(1)?;
    let top = kt::simplices_of_dim(&complex, dim);
    if terms.iter().any(|(_, s)| s.len() != dim + 1 || !top.contains(s)) {
        return None;
    }
    if dim == 0 {
        return Some(V::List(Vec::new()));
    }
    let faces = kt::simplices_of_dim(&complex, dim - 1);
    let mut out = Vec::new();
    for face in &faces {
        let mut parts = Vec::new();
        for (c, s) in &terms {
            for (sign, f) in kt::simplex_boundary(s) {
                if &f == face {
                    let sign = cx.graph.int(sign);
                    parts.push(prod(cx.graph, &[sign, *c]));
                }
            }
        }
        if parts.is_empty() {
            continue;
        }
        let total = sum(cx.graph, &parts);
        let total = cx.simplify(total);
        if !is_zero(cx.graph, total) {
            out.push(V::List(vec![V::Node(total), simplex_v(face)]));
        }
    }
    Some(V::List(out))
}

fn sc_betti(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [k, d] = a else { return None };
    let complex = read_complex(cx.graph, *k)?;
    Some(V::uint(kt::betti_number(&complex, idx(cx.graph, *d)?)))
}

fn sc_cohomology_betti(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [k, d] = a else { return None };
    let complex = read_complex(cx.graph, *k)?;
    Some(V::uint(kt::cohomology_betti_number(&complex, idx(cx.graph, *d)?)))
}

fn sc_verify_boundary(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    Some(V::Bool(kt::verify_boundary_property(&complex_arg(cx, a)?)))
}

fn sc_verify_coboundary(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    Some(V::Bool(kt::verify_coboundary_property(&complex_arg(cx, a)?)))
}

fn sc_components(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let complex = complex_arg(cx, a)?;
    let vertices: Vec<usize> = kt::simplices_of_dim(&complex, 0).into_iter().map(|s| s[0]).collect();
    let pos = |v: usize| vertices.binary_search(&v).ok();
    let mut adj = vec![Vec::new(); vertices.len()];
    for e in kt::simplices_of_dim(&complex, 1) {
        let (u, v) = (pos(e[0])?, pos(e[1])?);
        adj[u].push(v);
        adj[v].push(u);
    }
    let comps = kt::find_connected_components(&adj);
    Some(V::List(
        comps
            .into_iter()
            .map(|c| {
                let mut c: Vec<usize> = c.into_iter().map(|i| vertices[i]).collect();
                c.sort_unstable();
                simplex_v(&c)
            })
            .collect(),
    ))
}

fn sc_grid(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [w, h] = a else { return None };
    let (w, h) = (count(cx.graph, *w, 200)?, count(cx.graph, *h, 200)?);
    complex_v(cx.graph, &kt::grid_complex(w, h))
}

fn sc_torus(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [m, n] = a else { return None };
    let (m, n) = (count(cx.graph, *m, 200)?, count(cx.graph, *n, 200)?);
    if m < 3 || n < 3 {
        return None;
    }
    complex_v(cx.graph, &kt::torus_complex(m, n))
}

