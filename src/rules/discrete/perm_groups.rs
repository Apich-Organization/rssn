/// The generators of a permutation group term: degree and permutations.
fn read_gens(
    g: &Graph,
    n: NodeId,
) -> Option<(usize, Vec<Perm>)> {
    let list = items(g, n)?;
    let mut perms = Vec::new();
    for p in list {
        perms.push(read_perm(g, p)?);
    }
    let degree = perms.first()?.len();
    if perms.iter().any(|p| p.len() != degree) || degree == 0 || degree > 64 {
        return None;
    }
    Some((degree, perms))
}

/// A permutation as 0-based images.
pub(crate) fn read_perm(
    g: &Graph,
    n: NodeId,
) -> Option<Perm> {
    let images = super::idxs(g, n)?;
    let m = images.len();
    let mut seen = vec![false; m];
    let mut out = Vec::with_capacity(m);
    for v in images {
        let v = v.checked_sub(1).filter(|&v| v < m)?;
        if std::mem::replace(&mut seen[v], true) {
            return None;
        }
        out.push(v);
    }
    Some(out)
}

fn perm_node(
    g: &mut Graph,
    p: &[usize],
) -> NodeId {
    let nodes: Vec<NodeId> = p.iter().map(|&x| g.int(i64::try_from(x + 1).unwrap_or(0))).collect();
    super::list(g, &nodes)
}

/// The group term of the permutation group generated by `gens` of degree
/// `n`, if its order is at most [`TABLE_LIMIT`].
pub(crate) fn perm_group_term(
    g: &mut Graph,
    n: usize,
    gens: &[Perm],
) -> Option<V> {
    let chain = Chain::new(n, gens);
    let elems = chain.elements(TABLE_LIMIT)?;
    let pos: HashMap<&Perm, usize> = elems.iter().enumerate().map(|(i, p)| (p, i)).collect();
    let mut table = Vec::with_capacity(elems.len());
    for p in &elems {
        let mut row = Vec::with_capacity(elems.len());
        for q in &elems {
            row.push(*pos.get(&compose(p, q))?);
        }
        table.push(row);
    }
    let nodes: Vec<NodeId> = elems.iter().map(|p| perm_node(g, p)).collect();
    build_group(g, &nodes, &table)
}

fn chain_of(
    cx: &Cx<'_>,
    a: &[NodeId],
) -> Option<Chain> {
    let (n, gens) = read_gens(cx.graph, *a.first()?)?;
    Some(Chain::new(n, &gens))
}

fn perm_group_order(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    Some(V::Int(chain_of(cx, a)?.order()))
}

fn perm_group_contains(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [gens, p] = a else { return None };
    let (n, gens) = read_gens(cx.graph, *gens)?;
    let p = read_perm(cx.graph, *p)?;
    if p.len() != n {
        return Some(V::Bool(false));
    }
    Some(V::Bool(Chain::new(n, &gens).contains(&p)))
}

fn perm_group_base(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let c = chain_of(cx, a)?;
    Some(V::ints(c.base().iter().map(|&b| i64::try_from(b + 1).unwrap_or(0))))
}

fn perm_group_strong_generators(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let c = chain_of(cx, a)?;
    Some(V::List(c.strong_generators().iter().map(|p| perm_v(p)).collect()))
}

fn perm_group_basic_orbits(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let c = chain_of(cx, a)?;
    Some(V::ints(c.basic_orbit_lengths().into_iter().map(|l| i64::try_from(l).unwrap_or(0))))
}

fn perm_group_orbits(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let c = chain_of(cx, a)?;
    Some(V::List(
        c.orbits().iter().map(|o| V::ints(o.iter().map(|&x| i64::try_from(x + 1).unwrap_or(0)))).collect(),
    ))
}

fn perm_group_is_transitive(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    Some(V::Bool(chain_of(cx, a)?.orbits().len() == 1))
}

fn perm_group_stabilizer_order(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [gens, pt] = a else { return None };
    let (n, gens) = read_gens(cx.graph, *gens)?;
    let pt = idx(cx.graph, *pt)?.checked_sub(1).filter(|&p| p < n)?;
    Some(V::Int(Chain::new(n, &gens).stabilizer_order(pt)))
}

fn perm_group_elements(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let c = chain_of(cx, a)?;
    Some(V::List(c.elements(ELEMENT_LIMIT)?.iter().map(|p| perm_v(p)).collect()))
}

fn group_from_perms(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, gens) = read_gens(cx.graph, *a.first()?)?;
    perm_group_term(cx.graph, n, &gens)
}

fn perm_group_is_abelian(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (_, gens) = read_gens(cx.graph, *a.first()?)?;
    Some(V::Bool(gens.iter().all(|x| gens.iter().all(|y| compose(x, y) == compose(y, x)))))
}

fn orders_v(orders: Vec<BigInt>) -> V {
    V::List(orders.into_iter().map(V::Int).collect())
}

fn perm_group_derived_series(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, gens) = read_gens(cx.graph, *a.first()?)?;
    Some(orders_v(derived_series(n, &gens)))
}

fn perm_group_is_solvable(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, gens) = read_gens(cx.graph, *a.first()?)?;
    Some(V::Bool(derived_series(n, &gens).last().is_some_and(|o| *o == BigInt::from(1))))
}

fn perm_group_lower_central_series(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, gens) = read_gens(cx.graph, *a.first()?)?;
    Some(orders_v(lower_central_series(n, &gens)))
}

fn perm_group_is_nilpotent(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, gens) = read_gens(cx.graph, *a.first()?)?;
    Some(V::Bool(lower_central_series(n, &gens).last().is_some_and(|o| *o == BigInt::from(1))))
}

fn perm_group_derived_subgroup(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, gens) = read_gens(cx.graph, *a.first()?)?;
    let d = derived_subgroup(n, &gens);
    let g = d.strong_generators();
    if g.is_empty() {
        return Some(V::List(vec![perm_v(&identity(n))]));
    }
    Some(V::List(g.iter().map(|p| perm_v(p)).collect()))
}

