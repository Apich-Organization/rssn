/// A permutation as 0-based images.
pub(crate) type Perm = Vec<usize>;

/// The largest order for which all elements are listed.
const ELEMENT_LIMIT: usize = 5040;
/// The largest order for which a table is built.
pub(crate) const TABLE_LIMIT: usize = 720;
/// The largest number of cosets of a Todd–Coxeter enumeration.
const COSET_LIMIT: usize = 400_000;

pub(crate) fn identity(n: usize) -> Perm {
    (0..n).collect()
}

/// `a ∘ b`: apply `b` first.
pub(crate) fn compose(
    a: &[usize],
    b: &[usize],
) -> Perm {
    b.iter().map(|&x| a[x]).collect()
}

pub(crate) fn inverse(p: &[usize]) -> Perm {
    let mut inv = vec![0; p.len()];
    for (i, &x) in p.iter().enumerate() {
        inv[x] = i;
    }
    inv
}

pub(crate) fn is_identity(p: &[usize]) -> bool {
    p.iter().enumerate().all(|(i, &x)| i == x)
}

/// `a^-1 b^-1 a b`.
fn commutator(
    a: &[usize],
    b: &[usize],
) -> Perm {
    compose(&compose(&inverse(a), &inverse(b)), &compose(a, b))
}

/// A stabiliser chain.
#[derive(Clone, Debug)]
pub(crate) struct Chain {
    n: usize,
    base: Vec<usize>,
    gens: Vec<Vec<Perm>>,
    trans: Vec<Vec<Option<Perm>>>,
    orbit: Vec<Vec<usize>>,
}

impl Chain {
    /// The chain of the group generated by `gens` (all of degree `n`).
    pub(crate) fn new(
        n: usize,
        gens: &[Perm],
    ) -> Self {
        let mut c = Self { n, base: Vec::new(), gens: Vec::new(), trans: Vec::new(), orbit: Vec::new() };
        for g in gens {
            if !is_identity(g) {
                c.insert_generator(g);
            }
        }
        c.complete(c.base.len());
        c
    }

    fn recompute_orbit(
        &mut self,
        level: usize,
    ) {
        let b = self.base[level];
        let mut trans: Vec<Option<Perm>> = vec![None; self.n];
        trans[b] = Some(identity(self.n));
        let mut orbit = vec![b];
        let mut head = 0;
        while head < orbit.len() {
            let pt = orbit[head];
            head += 1;
            let u = trans[pt].clone().unwrap_or_default();
            for s in &self.gens[level] {
                let img = s[pt];
                if trans[img].is_none() {
                    trans[img] = Some(compose(s, &u));
                    orbit.push(img);
                }
            }
        }
        self.trans[level] = trans;
        self.orbit[level] = orbit;
    }

    /// Sifts `g` through the levels from `from` on; returns the residue and
    /// the level at which it got stuck (`base.len()` if it went through).
    fn sift(
        &self,
        mut g: Perm,
        from: usize,
    ) -> (Perm, usize) {
        for l in from..self.base.len() {
            let pt = g[self.base[l]];
            match &self.trans[l][pt] {
                | Some(u) => g = compose(&inverse(u), &g),
                | None => return (g, l),
            }
        }
        (g, self.base.len())
    }

    /// Adds the non-identity residue `r` as a strong generator of the levels
    /// `from..=to` (creating a level if `to` is the depth).
    fn add_strong(
        &mut self,
        r: &Perm,
        from: usize,
        to: usize,
    ) {
        if to == self.base.len() {
            let b = (0..self.n).find(|&x| r[x] != x).unwrap_or(0);
            self.base.push(b);
            self.gens.push(Vec::new());
            self.trans.push(Vec::new());
            self.orbit.push(Vec::new());
        }
        for m in from..=to {
            self.gens[m].push(r.clone());
            self.recompute_orbit(m);
        }
    }

    fn insert_generator(
        &mut self,
        g: &Perm,
    ) {
        let (r, j) = self.sift(g.clone(), 0);
        if !is_identity(&r) {
            self.add_strong(&r, 0, j);
        }
    }

    /// Verifies the Schreier generators from level `start - 1` upwards and
    /// repairs the chain.
    fn complete(
        &mut self,
        start: usize,
    ) {
        let mut i = start;
        while i > 0 {
            let l = i - 1;
            let mut added = None;
            'outer: for &pt in &self.orbit[l].clone() {
                for s in &self.gens[l].clone() {
                    let img = s[pt];
                    let (Some(up), Some(ui)) = (&self.trans[l][pt], &self.trans[l][img]) else { continue };
                    let h = compose(&inverse(ui), &compose(s, up));
                    let (r, j) = self.sift(h, l + 1);
                    if !is_identity(&r) {
                        self.add_strong(&r, l + 1, j);
                        added = Some(j + 1);
                        break 'outer;
                    }
                }
            }
            match added {
                | Some(next) => i = next,
                | None => i -= 1,
            }
        }
    }

    /// Adds `g` to the group.
    pub(crate) fn insert(
        &mut self,
        g: &Perm,
    ) {
        let (r, j) = self.sift(g.clone(), 0);
        if !is_identity(&r) {
            self.add_strong(&r, 0, j);
            let depth = self.base.len();
            self.complete(depth);
        }
    }

    /// Whether `g` lies in the group.
    pub(crate) fn contains(
        &self,
        g: &[usize],
    ) -> bool {
        g.len() == self.n && {
            let (r, l) = self.sift(g.to_vec(), 0);
            l == self.base.len() && is_identity(&r)
        }
    }

    pub(crate) fn order(&self) -> BigInt {
        self.orbit.iter().fold(BigInt::from(1), |acc, o| acc * o.len())
    }

    pub(crate) fn base(&self) -> &[usize] {
        &self.base
    }

    pub(crate) fn basic_orbit_lengths(&self) -> Vec<usize> {
        self.orbit.iter().map(Vec::len).collect()
    }

    /// The strong generators (without repetition), level by level.
    pub(crate) fn strong_generators(&self) -> Vec<Perm> {
        let mut seen = HashSet::new();
        let mut out = Vec::new();
        for level in &self.gens {
            for g in level {
                if seen.insert(g.clone()) {
                    out.push(g.clone());
                }
            }
        }
        out
    }

    /// The order of the stabiliser of `point`, by a chain with `point`
    /// first in the base.
    pub(crate) fn stabilizer_order(
        &self,
        point: usize,
    ) -> BigInt {
        let gens = self.strong_generators();
        let mut c = Self { n: self.n, base: Vec::new(), gens: Vec::new(), trans: Vec::new(), orbit: Vec::new() };
        // Force `point` to be the first base point by a first level with
        // (possibly) no generators moving it.
        c.base.push(point);
        c.gens.push(Vec::new());
        c.trans.push(Vec::new());
        c.orbit.push(Vec::new());
        for g in &gens {
            if !is_identity(g) {
                c.gens[0].push(g.clone());
            }
        }
        c.recompute_orbit(0);
        c.complete(1);
        // The chain was seeded with the generators at level 0 only; sift
        // them through the deeper levels to make the chain a proper one.
        let seeds = c.gens[0].clone();
        for g in &seeds {
            c.insert(g);
        }
        let total = c.order();
        total / c.orbit[0].len()
    }

    /// All elements, by products of coset representatives, if there are at
    /// most `limit`.
    pub(crate) fn elements(
        &self,
        limit: usize,
    ) -> Option<Vec<Perm>> {
        if self.order() > BigInt::from(limit) {
            return None;
        }
        let mut all = vec![identity(self.n)];
        for l in (0..self.base.len()).rev() {
            let reps: Vec<&Perm> = self.trans[l].iter().flatten().collect();
            let mut next = Vec::with_capacity(all.len() * reps.len());
            for u in reps {
                for g in &all {
                    next.push(compose(u, g));
                }
            }
            all = next;
        }
        all.sort();
        Some(all)
    }

    /// The orbits on the points, each sorted.
    pub(crate) fn orbits(&self) -> Vec<Vec<usize>> {
        let gens = self.strong_generators();
        orbits_of(self.n, &gens)
    }
}

pub(crate) fn orbits_of(
    n: usize,
    gens: &[Perm],
) -> Vec<Vec<usize>> {
    let mut seen = vec![false; n];
    let mut out = Vec::new();
    for start in 0..n {
        if seen[start] {
            continue;
        }
        let mut orbit = vec![start];
        seen[start] = true;
        let mut head = 0;
        while head < orbit.len() {
            let pt = orbit[head];
            head += 1;
            for g in gens {
                if !seen[g[pt]] {
                    seen[g[pt]] = true;
                    orbit.push(g[pt]);
                }
            }
        }
        orbit.sort_unstable();
        out.push(orbit);
    }
    out
}

/// The normal closure in `<group_gens>` of `subset`.
fn normal_closure(
    n: usize,
    group_gens: &[Perm],
    subset: &[Perm],
) -> Chain {
    let mut chain = Chain::new(n, subset);
    loop {
        let mut changed = false;
        for h in chain.strong_generators() {
            for g in group_gens {
                let c = compose(&compose(g, &h), &inverse(g));
                if !chain.contains(&c) {
                    chain.insert(&c);
                    changed = true;
                }
            }
        }
        if !changed {
            return chain;
        }
    }
}

/// The derived subgroup of `<gens>`.
pub(crate) fn derived_subgroup(
    n: usize,
    gens: &[Perm],
) -> Chain {
    let mut commutators = Vec::new();
    for (i, a) in gens.iter().enumerate() {
        for b in &gens[i + 1..] {
            commutators.push(commutator(a, b));
        }
    }
    normal_closure(n, gens, &commutators)
}

/// `[<sub>, <gens>]` for a normal subgroup `<sub>`.
fn commutator_with(
    n: usize,
    gens: &[Perm],
    sub: &[Perm],
) -> Chain {
    let mut commutators = Vec::new();
    for a in sub {
        for g in gens {
            commutators.push(commutator(a, g));
        }
    }
    normal_closure(n, gens, &commutators)
}

/// The orders of the derived series, ending at the first repeated term.
pub(crate) fn derived_series(
    n: usize,
    gens: &[Perm],
) -> Vec<BigInt> {
    let mut chain = Chain::new(n, gens);
    let mut out = vec![chain.order()];
    loop {
        let g = chain.strong_generators();
        let next = derived_subgroup(n, &g);
        let o = next.order();
        let stop = o == *out.last().unwrap_or(&o);
        if !stop {
            out.push(o);
        }
        if stop || next.order() == BigInt::from(1) {
            return out;
        }
        chain = next;
    }
}

/// The orders of the lower central series, ending at the first repeat.
pub(crate) fn lower_central_series(
    n: usize,
    gens: &[Perm],
) -> Vec<BigInt> {
    let all = Chain::new(n, gens).strong_generators();
    let mut cur = all.clone();
    let mut out = vec![Chain::new(n, &all).order()];
    loop {
        let next = commutator_with(n, &all, &cur);
        let o = next.order();
        if o == *out.last().unwrap_or(&o) {
            return out;
        }
        let trivial = o == BigInt::from(1);
        out.push(o);
        if trivial {
            return out;
        }
        cur = next.strong_generators();
    }
}

