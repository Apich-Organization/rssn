const NONE: usize = usize::MAX;

/// A coset table under construction (HLT strategy).
struct Cosets {
    ncols: usize,
    table: Vec<usize>,
    parent: Vec<usize>,
    live: usize,
}

impl Cosets {
    fn new(ngens: usize) -> Self {
        let mut c = Self { ncols: 2 * ngens, table: Vec::new(), parent: Vec::new(), live: 0 };
        c.new_coset();
        c
    }

    fn new_coset(&mut self) -> usize {
        let id = self.parent.len();
        self.parent.push(id);
        self.table.extend(std::iter::repeat_n(NONE, self.ncols));
        self.live += 1;
        id
    }

    fn rep(
        &mut self,
        mut k: usize,
    ) -> usize {
        let mut root = k;
        while self.parent[root] != root {
            root = self.parent[root];
        }
        while self.parent[k] != root {
            let next = self.parent[k];
            self.parent[k] = root;
            k = next;
        }
        root
    }

    fn get(
        &self,
        c: usize,
        x: usize,
    ) -> usize {
        self.table[c * self.ncols + x]
    }

    fn set(
        &mut self,
        c: usize,
        x: usize,
        v: usize,
    ) {
        self.table[c * self.ncols + x] = v;
    }

    fn merge(
        &mut self,
        k: usize,
        l: usize,
        queue: &mut Vec<usize>,
    ) {
        let (k, l) = (self.rep(k), self.rep(l));
        if k != l {
            let (mu, nu) = (k.min(l), k.max(l));
            self.parent[nu] = mu;
            self.live -= 1;
            queue.push(nu);
        }
    }

    fn coincidence(
        &mut self,
        a: usize,
        b: usize,
    ) {
        let mut queue = Vec::new();
        self.merge(a, b, &mut queue);
        let mut i = 0;
        while i < queue.len() {
            let gamma = queue[i];
            i += 1;
            for x in 0..self.ncols {
                let delta = self.get(gamma, x);
                if delta == NONE {
                    continue;
                }
                self.set(delta, x ^ 1, NONE);
                let mu = self.rep(gamma);
                let nu = self.rep(delta);
                let t = self.get(mu, x);
                if t == NONE {
                    let t2 = self.get(nu, x ^ 1);
                    if t2 == NONE {
                        self.set(mu, x, nu);
                        self.set(nu, x ^ 1, mu);
                    } else {
                        self.merge(mu, t2, &mut queue);
                    }
                } else {
                    self.merge(nu, t, &mut queue);
                }
            }
        }
    }

    /// Scans the word `w` (columns) from coset `c`, defining cosets as
    /// needed.
    fn scan_and_fill(
        &mut self,
        c: usize,
        w: &[usize],
    ) -> bool {
        let (mut f, mut b) = (c, c);
        let (mut i, mut j) = (0_usize, w.len());
        // `j` is one past the last unscanned letter.
        loop {
            while i < j && self.get(f, w[i]) != NONE {
                f = self.get(f, w[i]);
                i += 1;
            }
            if i == j {
                if f != b {
                    self.coincidence(f, b);
                }
                return true;
            }
            while j > i && self.get(b, w[j - 1] ^ 1) != NONE {
                b = self.get(b, w[j - 1] ^ 1);
                j -= 1;
            }
            if j == i {
                self.coincidence(f, b);
                return true;
            }
            if j == i + 1 {
                self.set(f, w[i], b);
                self.set(b, w[i] ^ 1, f);
                return true;
            }
            if self.parent.len() >= COSET_LIMIT {
                return false;
            }
            let n = self.new_coset();
            self.set(f, w[i], n);
            self.set(n, w[i] ^ 1, f);
        }
    }
}

/// The coset table of `<gens | relators>` over the subgroup `subgens`:
/// the number of cosets and, for each generator, its action on them
/// (0-based images).
pub(crate) fn todd_coxeter_table(
    ngens: usize,
    relators: &[Vec<usize>],
    subgens: &[Vec<usize>],
) -> Option<(usize, Vec<Perm>)> {
    let mut t = Cosets::new(ngens);
    for w in subgens {
        if !t.scan_and_fill(0, w) {
            return None;
        }
    }
    let mut c = 0;
    while c < t.parent.len() {
        if t.parent[c] == c {
            for w in relators {
                if t.parent[c] != c {
                    break;
                }
                if !t.scan_and_fill(c, w) {
                    return None;
                }
            }
            if t.parent[c] == c {
                for x in 0..t.ncols {
                    if t.parent[c] == c && t.get(c, x) == NONE {
                        if t.parent.len() >= COSET_LIMIT {
                            return None;
                        }
                        let n = t.new_coset();
                        t.set(c, x, n);
                        t.set(n, x ^ 1, c);
                    }
                }
            }
        }
        c += 1;
    }
    // Compress.
    let live: Vec<usize> = (0..t.parent.len()).filter(|&k| t.parent[k] == k).collect();
    let pos: HashMap<usize, usize> = live.iter().enumerate().map(|(i, &k)| (k, i)).collect();
    let mut perms = vec![vec![0; live.len()]; ngens];
    for (i, &k) in live.iter().enumerate() {
        for (g, perm) in perms.iter_mut().enumerate() {
            let img = t.get(k, 2 * g);
            perm[i] = *pos.get(&t.rep(img))?;
        }
    }
    Some((live.len(), perms))
}

/// Reads a word over the generators `gens` into columns (`2i` for the
/// generator `i`, `2i + 1` for its inverse).
fn read_word(
    g: &Graph,
    gens: &[NodeId],
    word: NodeId,
) -> Option<Vec<usize>> {
    let letters = items(g, word)?;
    let mut out = Vec::new();
    for l in letters {
        read_letter(g, gens, l, &mut out)?;
    }
    Some(out)
}

fn read_letter(
    g: &Graph,
    gens: &[NodeId],
    l: NodeId,
    out: &mut Vec<usize>,
) -> Option<()> {
    let pos = |n: NodeId| gens.iter().position(|&s| g.same(s, n));
    if let Some(i) = pos(l) {
        out.push(2 * i);
        return Some(());
    }
    if let Some(v) = super::small(g, l) {
        let i = usize::try_from(v.unsigned_abs()).ok()?.checked_sub(1).filter(|&i| i < gens.len())?;
        out.push(2 * i + usize::from(v < 0));
        return Some(());
    }
    if g.op(l) == core::POW {
        let [b, e] = g.children(l) else { return None };
        let i = pos(*b)?;
        let k = super::small(g, *e)?;
        if k.unsigned_abs() > 10_000 {
            return None;
        }
        for _ in 0..k.unsigned_abs() {
            out.push(2 * i + usize::from(k < 0));
        }
        return Some(());
    }
    None
}

/// The number of generators, the relators and the subgroup generators.
type Presentation = (usize, Vec<Vec<usize>>, Vec<Vec<usize>>);

/// Reads a presentation: generators, relators and subgroup generators.
fn read_presentation(
    g: &Graph,
    a: &[NodeId],
) -> Option<Presentation> {
    let gens = items(g, *a.first()?)?;
    if gens.is_empty() {
        return None;
    }
    let rels: Vec<Vec<usize>> = items(g, *a.get(1)?)?.into_iter().map(|w| read_word(g, &gens, w)).collect::<Option<_>>()?;
    let subs: Vec<Vec<usize>> = match a.get(2) {
        | Some(&s) => items(g, s)?.into_iter().map(|w| read_word(g, &gens, w)).collect::<Option<_>>()?,
        | None => Vec::new(),
    };
    Some((gens.len(), rels, subs))
}

fn perm_v(p: &[usize]) -> V {
    V::ints(p.iter().map(|&x| i64::try_from(x + 1).unwrap_or(0)))
}

fn todd_coxeter(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, rels, subs) = read_presentation(cx.graph, a)?;
    let (index, perms) = todd_coxeter_table(n, &rels, &subs)?;
    Some(V::List(vec![V::uint(index), V::List(perms.iter().map(|p| perm_v(p)).collect())]))
}

fn todd_coxeter_index(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, rels, subs) = read_presentation(cx.graph, a)?;
    Some(V::uint(todd_coxeter_table(n, &rels, &subs)?.0))
}

fn fp_group_order(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, rels, _) = read_presentation(cx.graph, a)?;
    Some(V::uint(todd_coxeter_table(n, &rels, &[])?.0))
}

fn fp_group(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (n, rels, _) = read_presentation(cx.graph, a)?;
    let (index, perms) = todd_coxeter_table(n, &rels, &[])?;
    if index > TABLE_LIMIT {
        return None;
    }
    perm_group_term(cx.graph, index, &perms)
}

