/// The character table of a group.
pub(crate) struct CharTable {
    pub(crate) classes: Vec<Vec<usize>>,
    pub(crate) class_of: Vec<usize>,
    pub(crate) reps: Vec<usize>,
    pub(crate) sizes: Vec<usize>,
    pub(crate) degrees: Vec<usize>,
    pub(crate) rows: Vec<Vec<Entry>>,
    pub(crate) z: Vec<Vec<Complex64>>,
    pub(crate) inv_class: Vec<usize>,
    pub(crate) n: usize,
}

impl CharTable {
    /// `(1/|G|) sum_g a(g) conj(b(g))` over class functions.
    pub(crate) fn inner(
        &self,
        a: &[Complex64],
        b: &[Complex64],
    ) -> Complex64 {
        let s: Complex64 = (0..self.classes.len()).map(|i| a[i] * b[i].conj() * self.sizes[i] as f64).sum();
        s / self.n as f64
    }

    /// The multiplicities of the irreducibles in a class function.
    pub(crate) fn decompose(
        &self,
        chi: &[Complex64],
    ) -> Option<Vec<i64>> {
        self.z
            .iter()
            .map(|row| {
                let m = self.inner(chi, row);
                let r = m.re.round();
                (m.im.abs() < 1e-6 && (m.re - r).abs() < 1e-6).then_some(r as i64)
            })
            .collect()
    }
}

/// Class function values from a list of terms: one per class or per element.
pub(crate) fn read_class_function(
    g: &Graph,
    ct: &CharTable,
    n: NodeId,
) -> Option<Vec<Complex64>> {
    let list = items(g, n)?;
    let bindings = HashMap::new();
    let vals: Vec<Complex64> = list.iter().map(|&x| g.eval_complex(x, &bindings)).collect::<Option<_>>()?;
    if vals.len() == ct.classes.len() {
        Some(vals)
    } else if vals.len() == ct.n {
        Some(ct.reps.iter().map(|&r| vals[r]).collect())
    } else {
        None
    }
}

fn find_prime(
    n: usize,
    e: usize,
    k: usize,
) -> u64 {
    let lower = (n as u64).max(16 * (k * k) as u64);
    let mut j = 1;
    loop {
        let p = (e * j + 1) as u64;
        if p > lower && is_prime(p) {
            return p;
        }
        j += 1;
    }
}

fn isqrt_exact(v: u64) -> Option<u64> {
    let r = (v as f64).sqrt().round() as u64;
    (r.saturating_sub(1)..=r + 1).find(|&c| c * c == v)
}

/// The character table of the group with multiplication table `t`.
#[allow(clippy::too_many_lines)] // one algorithm: constants, eigenvectors, degrees, lifting
pub(crate) fn character_table(t: &Tab) -> Option<CharTable> {
    let n = t.n;
    let classes = t.classes();
    let k = classes.len();
    let mut class_of = vec![0; n];
    for (i, c) in classes.iter().enumerate() {
        for &x in c {
            class_of[x] = i;
        }
    }
    let reps: Vec<usize> = classes.iter().map(|c| c[0]).collect();
    let sizes: Vec<usize> = classes.iter().map(Vec::len).collect();
    let inv_class: Vec<usize> = reps.iter().map(|&r| class_of[t.inv[r]]).collect();
    let id_class = class_of[t.id];
    let e = (0..n).fold(1, |acc, x| acc.lcm(&t.order(x)));
    let p = find_prime(n, e, k);

    // Class multiplication constants a[j][i][l] = #{(x, y) in C_i x C_j : xy = z_l}.
    let mut a = vec![vec![vec![0_u64; k]; k]; k];
    for (l, &z) in reps.iter().enumerate() {
        for x in 0..n {
            let y = t.m(t.inv[x], z);
            a[class_of[y]][class_of[x]][l] += 1;
        }
    }
    // Eigen-decomposition of a random combination of the class matrices.
    let mut seed = 0x9E37_79B9_7F4A_7C15_u64;
    let mut next = || {
        seed = seed.wrapping_mul(6_364_136_223_846_793_005).wrapping_add(1_442_695_040_888_963_407);
        (seed >> 33) % p
    };
    let mut omegas: Option<Vec<Vec<u64>>> = None;
    for attempt in 0..60 {
        let coeffs: Vec<u64> = (0..k).map(|j| if attempt == 0 { j as u64 + 1 } else { next() }).collect();
        let mut m = vec![vec![0_u64; k]; k];
        for j in 0..k {
            for i in 0..k {
                for l in 0..k {
                    m[i][l] = (m[i][l] + coeffs[j] * a[j][i][l]) % p;
                }
            }
        }
        let cp = charpoly(&m, p);
        let roots: Vec<u64> = (0..p).filter(|&x| eval_poly(&cp, x, p) == 0).collect();
        if roots.len() != k {
            continue;
        }
        let mut vecs = Vec::new();
        for &lam in &roots {
            let mut shifted = m.clone();
            for (i, row) in shifted.iter_mut().enumerate() {
                row[i] = (row[i] + p - lam) % p;
            }
            let Some(mut w) = null_vector(shifted, p) else { break };
            if w[id_class] == 0 {
                break;
            }
            let inv = minv(w[id_class], p);
            for x in &mut w {
                *x = *x * inv % p;
            }
            vecs.push(w);
        }
        if vecs.len() == k {
            omegas = Some(vecs);
            break;
        }
    }
    let omegas = omegas?;

    // A primitive e-th root of unity modulo p.
    let primes: Vec<u64> = (2..=e as u64).filter(|&q| (e as u64).is_multiple_of(q) && is_prime(q)).collect();
    let root_e = (2..p)
        .map(|h| mpow(h, (p - 1) / e as u64, p))
        .find(|&r| mpow(r, e as u64, p) == 1 && primes.iter().all(|&q| mpow(r, e as u64 / q, p) != 1))
        .unwrap_or(1);

    let mut rows_raw: Vec<(usize, Vec<Entry>)> = Vec::new();
    for w in &omegas {
        // chi(1)^2 = |G| / sum_i w_i w_{i'} / |C_i|
        let mut s = 0;
        for i in 0..k {
            let term = w[i] * w[inv_class[i]] % p * minv(sizes[i] as u64 % p, p) % p;
            s = (s + term) % p;
        }
        let d2 = n as u64 % p * minv(s, p) % p;
        let d = isqrt_exact(d2)?;
        let chi_p: Vec<u64> = (0..k).map(|i| d % p * w[i] % p * minv(sizes[i] as u64 % p, p) % p).collect();
        let mut entries = Vec::with_capacity(k);
        for i in 0..k {
            let g = reps[i];
            let m = t.order(g);
            let omega_m = mpow(root_e, (e / m) as u64, p);
            let inv_m = minv(m as u64 % p, p);
            let mut v_m = vec![0_i64; m];
            let mut total = 0;
            for j in 0..m {
                let mut acc = 0;
                for tt in 0..m {
                    let val = chi_p[class_of[t.pow(g, tt)]];
                    let root = mpow(omega_m, ((m - j) * tt % m) as u64, p);
                    acc = (acc + val * root) % p;
                }
                let mult = acc * inv_m % p;
                if mult > d {
                    return None;
                }
                v_m[j] = mult as i64;
                total += mult;
            }
            if total != d {
                return None;
            }
            entries.push(Entry { m, v: v_m });
        }
        rows_raw.push((d as usize, entries));
    }
    let mut rows: Vec<(usize, Vec<Entry>, Vec<Complex64>)> = rows_raw
        .into_iter()
        .map(|(d, es)| {
            let z: Vec<Complex64> = es.iter().map(Entry::value).collect();
            (d, es, z)
        })
        .collect();
    rows.sort_by(|x, y| {
        x.0.cmp(&y.0).then_with(|| {
            for (a, b) in x.2.iter().zip(&y.2) {
                let (ra, rb) = ((a.re * 1e6).round(), (b.re * 1e6).round());
                if ra != rb {
                    return rb.total_cmp(&ra);
                }
                let (ia, ib) = ((a.im * 1e6).round(), (b.im * 1e6).round());
                if ia != ib {
                    return ib.total_cmp(&ia);
                }
            }
            std::cmp::Ordering::Equal
        })
    });
    let table = CharTable {
        classes,
        class_of,
        reps,
        sizes,
        degrees: rows.iter().map(|r| r.0).collect(),
        z: rows.iter().map(|r| r.2.clone()).collect(),
        rows: rows.into_iter().map(|r| r.1).collect(),
        inv_class,
        n,
    };
    table.verify().then_some(table)
}

impl CharTable {
    /// Row and column orthogonality, and `sum d^2 = |G|`.
    pub(crate) fn verify(&self) -> bool {
        let k = self.classes.len();
        if self.degrees.iter().map(|d| d * d).sum::<usize>() != self.n || self.z.len() != k {
            return false;
        }
        for (a, ra) in self.z.iter().enumerate() {
            for (b, rb) in self.z.iter().enumerate() {
                let ip = self.inner(ra, rb);
                let want = if a == b { 1.0 } else { 0.0 };
                if (ip.re - want).abs() > 1e-8 || ip.im.abs() > 1e-8 {
                    return false;
                }
            }
        }
        for i in 0..k {
            for j in 0..k {
                let s: Complex64 = self.z.iter().map(|r| r[i] * r[j].conj()).sum();
                let want = if i == j { self.n as f64 / self.sizes[i] as f64 } else { 0.0 };
                if (s.re - want).abs() > 1e-8 || s.im.abs() > 1e-8 {
                    return false;
                }
            }
        }
        true
    }

    /// The class of the `k`-th power of the elements of each class.
    pub(crate) fn power_classes(
        &self,
        t: &Tab,
        k: usize,
    ) -> Vec<usize> {
        self.reps.iter().map(|&r| self.class_of[t.pow(r, k)]).collect()
    }
}

