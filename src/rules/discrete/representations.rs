/// A character value: the sum of `v[k]` copies of `exp(2 pi i k / m)`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct Entry {
    pub(crate) m: usize,
    pub(crate) v: Vec<i64>,
}

impl Entry {
    pub(crate) fn value(&self) -> Complex64 {
        let m = self.m as f64;
        self.v
            .iter()
            .enumerate()
            .map(|(k, &c)| Complex64::from_polar(1.0, 2.0 * std::f64::consts::PI * k as f64 / m) * c as f64)
            .sum()
    }

    fn conj(&self) -> Self {
        let mut v = vec![0; self.m];
        for (k, &c) in self.v.iter().enumerate() {
            v[(self.m - k) % self.m] = c;
        }
        Self { m: self.m, v }
    }
}

/// The cyclotomic polynomial `Phi_m` as integer coefficients (low first).
fn cyclotomic(m: usize) -> Vec<i64> {
    let mut num = vec![0_i64; m + 1];
    num[0] = -1;
    num[m] = 1;
    for d in 1..m {
        if m.is_multiple_of(d) {
            let phi = cyclotomic(d);
            num = poly_div(&num, &phi);
        }
    }
    num
}

/// Exact division of integer polynomials by a monic divisor.
fn poly_div(
    a: &[i64],
    b: &[i64],
) -> Vec<i64> {
    let mut rem = a.to_vec();
    let (da, db) = (a.len() - 1, b.len() - 1);
    if da < db {
        return vec![0];
    }
    let mut q = vec![0; da - db + 1];
    for i in (0..=da - db).rev() {
        let c = rem[i + db];
        q[i] = c;
        for (j, &bj) in b.iter().enumerate() {
            rem[i + j] -= c * bj;
        }
    }
    q
}

/// Reduces an entry's coefficient vector by shifts of `Phi_m` while the
/// sum of absolute values decreases.
fn minimise(e: &Entry) -> Entry {
    let m = e.m;
    if m < 2 {
        return e.clone();
    }
    let phi = cyclotomic(m);
    let mut v = e.v.clone();
    let l1 = |v: &[i64]| v.iter().map(|c| c.abs()).sum::<i64>();
    loop {
        let mut best: Option<(i64, Vec<i64>)> = None;
        for shift in 0..m {
            for sign in [1_i64, -1] {
                let mut cand = v.clone();
                for (j, &c) in phi.iter().enumerate() {
                    cand[(j + shift) % m] += sign * c;
                }
                let n = l1(&cand);
                if n < best.as_ref().map_or_else(|| l1(&v), |b| b.0) {
                    best = Some((n, cand));
                }
            }
        }
        match best {
            | Some((_, cand)) => v = cand,
            | None => return Entry { m, v },
        }
    }
}

/// `(a + b sqrt(d)) / c` close to `x`, with `d` squarefree.
fn recognise_quadratic(x: f64) -> Option<(i64, i64, i64, i64)> {
    for c in [1_i64, 2, 3, 4, 6, 8, 12] {
        for d in [1_i64, 2, 3, 5, 6, 7, 10, 11, 13, 15] {
            let sq = (d as f64).sqrt();
            let max_b = if d == 1 { 0 } else { 24 };
            for bb in 0..=max_b {
                for b in if bb == 0 { vec![0] } else { vec![bb, -bb] } {
                    let a = (x * c as f64 - b as f64 * sq).round();
                    if (a + b as f64 * sq - x * c as f64).abs() < 1e-9 && a.abs() < 1e6 {
                        let a = a as i64;
                        let g = a.gcd(&b).gcd(&c);
                        let g = if g == 0 { 1 } else { g };
                        return Some((a / g, b / g, d, c / g));
                    }
                }
            }
        }
    }
    None
}

fn rat_node(
    g: &mut Graph,
    p: i64,
    q: i64,
) -> NodeId {
    match Number::fraction(p, q) {
        | Some(n) => g.num(n),
        | None => g.int(0),
    }
}

/// The exact term of a character value.
pub(crate) fn entry_node(
    g: &mut Graph,
    e: &Entry,
) -> NodeId {
    let e = minimise(e);
    let z = e.value();
    let nonzero: Vec<(usize, i64)> = e.v.iter().copied().enumerate().filter(|&(_, c)| c != 0).collect();
    if nonzero.is_empty() {
        return g.int(0);
    }
    if nonzero.len() == 1 && nonzero[0].0 == 0 {
        return g.int(nonzero[0].1);
    }
    if z.im.abs() < 1e-9
        && let Some((a, b, d, c)) = recognise_quadratic(z.re) {
            let mut terms = vec![rat_node(g, a, c)];
            if b != 0 {
                let dn = g.int(d);
                let sq = apply(g, "sqrt", &[dn]);
                if let Some(sq) = sq {
                    let coef = rat_node(g, b, c);
                    terms.push(prod(g, &[coef, sq]));
                }
            }
            return sum(g, &terms);
        }
    let pi = apply(g, "pi", &[]);
    let unit = apply(g, "I", &[]);
    let mut terms = Vec::new();
    for (k, c) in nonzero {
        // exp(2 pi i k / m), with k reduced to (-m/2, m/2]
        let m = e.m as i64;
        let mut kk = k as i64;
        if 2 * kk > m {
            kk -= m;
        }
        let exp = match (pi, unit) {
            | (Some(pi), Some(unit)) => {
                let q = rat_node(g, 2 * kk, m);
                let arg = prod(g, &[q, pi, unit]);
                apply(g, "exp", &[arg])
            },
            | _ => None,
        };
        let Some(exp) = exp else { return g.float(z.re) };
        if kk == 0 {
            terms.push(g.int(c));
        } else {
            let cn = g.int(c);
            terms.push(prod(g, &[cn, exp]));
        }
    }
    sum(g, &terms)
}

