//! Character theory of finite groups.
//!
//! The character table of a group is computed by the **Burnside–Dixon
//! algorithm**: the class multiplication constants give commuting *class
//! matrices* whose simultaneous eigenvectors are the central characters
//! `|C_i| chi(g_i) / chi(1)`. The eigenproblem is solved over the finite field
//! `F_p` with `p > |G|` and `p = 1 (mod exp G)`, where every eigenvalue
//! exists and the degrees come out as exact integers (`chi(1)^2 = |G| / S`).
//! The values are then lifted *exactly* to cyclotomic integers: restricting
//! to the cyclic group generated by a class representative `g` of order `m`,
//! the multiplicity of the eigenvalue `zeta_m^j` of `chi(g)` is
//! `(1/m) sum_t chi(g^t) zeta_m^(-jt)`, an integer in `0..=chi(1)` that is read
//! off modulo `p`. So every entry is a sum of roots of unity, e.g.
//! `exp(2*pi*I/3)`, and real quadratic entries such as the golden ratio
//! `(1 + sqrt(5))/2` of `A5` are recognised and written with radicals. The
//! table is verified by exact (numerical to `1e-8`) orthogonality before it
//! is returned.
//!
//! Rows are ordered by degree, then by decreasing values over the classes of
//! [`group_conjugacy_classes`](super::groups), so the trivial character
//! comes first. Columns follow the class order of `group_conjugacy_classes`.
//!
//! A *class function* is given as a list with one value per class (or one
//! value per group element); values may be any numeric terms, including
//! `exp(2*pi*I/3)`.
//!
//! | operator | value |
//! |---|---|
//! | `group_class_count(G)`, `group_class_sizes(G)`, `group_class_representatives(G)` | class data |
//! | `group_class_index(G, x)` | the 1-based index of the class of `x` |
//! | `group_character_table(G)` | list of the irreducible characters, one list of class values each |
//! | `group_character_degrees(G)` | their degrees |
//! | `character_table_is_orthogonal(G)` | row and column orthogonality of the computed table |
//! | `character_inner_product(G, chi, psi)` | `(1/|G|) sum chi(g) conj(psi(g))` |
//! | `character_is_irreducible(G, chi)` | `<chi, chi> = 1` |
//! | `character_decompose(G, chi)` | the multiplicities of the irreducibles (rows of the table) |
//! | `character_tensor(G, chi, psi)` | the pointwise product (tensor product) |
//! | `character_sym_square(G, chi)`, `character_alt_square(G, chi)` | `(chi(g)^2 + chi(g^2))/2`, `(chi(g)^2 - chi(g^2))/2` |
//! | `character_adams(G, chi, k)` | the Adams operation `g -> chi(g^k)` |
//! | `character_conjugate(G, chi)` | complex conjugate |
//! | `character_regular(G)` | the character of the regular representation |
//! | `character_of_matrices(G, mats)` | the class function of a matrix representation (traces at class representatives) |
//! | `representation_decompose(G, mats)` | its multiplicities of the irreducibles |
//! | `character_projection(G, i, mats)` | the projection `(d_i/|G|) sum conj(chi_i(g)) M(g)` onto the `i`-th isotypic component |

