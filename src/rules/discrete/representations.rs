fn table_of(
    cx: &mut Cx<'_>,
    n: NodeId,
) -> Option<(super::groups::Grp, Tab, CharTable)> {
    let (grp, t) = tab_of(cx, n)?;
    let ct = character_table(&t)?;
    Some((grp, t, ct))
}

fn classes_of(
    cx: &mut Cx<'_>,
    n: NodeId,
) -> Option<(super::groups::Grp, Tab, Vec<Vec<usize>>)> {
    let (grp, t) = tab_of(cx, n)?;
    let classes = t.classes();
    Some((grp, t, classes))
}

fn group_class_count(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (_, _, c) = classes_of(cx, *a.first()?)?;
    Some(V::uint(c.len()))
}

fn group_class_sizes(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (_, _, c) = classes_of(cx, *a.first()?)?;
    Some(V::List(c.iter().map(|x| V::uint(x.len())).collect()))
}

fn group_class_representatives(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (grp, _, c) = classes_of(cx, *a.first()?)?;
    Some(V::List(c.iter().map(|x| V::Node(grp.elems[x[0]])).collect()))
}

fn group_class_index(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, x] = a else { return None };
    let (grp, _, c) = classes_of(cx, *g)?;
    let x = lookup(cx, &grp.index, *x)?;
    Some(V::uint(c.iter().position(|cl| cl.contains(&x))? + 1))
}

fn table_nodes(
    g: &mut Graph,
    ct: &CharTable,
) -> V {
    V::List(
        ct.rows
            .iter()
            .map(|row| V::List(row.iter().map(|e| V::Node(entry_node(g, e))).collect()))
            .collect(),
    )
}

fn group_character_table(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (_, _, ct) = table_of(cx, *a.first()?)?;
    Some(table_nodes(cx.graph, &ct))
}

fn group_character_degrees(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (_, _, ct) = table_of(cx, *a.first()?)?;
    Some(V::List(ct.degrees.iter().map(|&d| V::uint(d)).collect()))
}

fn character_table_is_orthogonal(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (_, t) = tab_of(cx, *a.first()?)?;
    Some(V::Bool(character_table(&t).is_some()))
}

fn two_functions(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<(CharTable, Vec<Complex64>, Vec<Complex64>)> {
    let [g, x, y] = a else { return None };
    let (_, _, ct) = table_of(cx, *g)?;
    let x = read_class_function(cx.graph, &ct, *x)?;
    let y = read_class_function(cx.graph, &ct, *y)?;
    Some((ct, x, y))
}

fn character_inner_product(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (ct, x, y) = two_functions(cx, a)?;
    let ip = ct.inner(&x, &y);
    if (ip.im).abs() > 1e-9 {
        return None;
    }
    let scaled = ip.re * ct.n as f64;
    if (scaled - scaled.round()).abs() > 1e-7 {
        return Some(V::Float(ip.re));
    }
    let num = scaled.round() as i64;
    let den = ct.n as i64;
    let g = num.gcd(&den);
    let (num, den) = (num / g, den / g);
    if den == 1 {
        Some(V::int(num))
    } else {
        let node = rat_node(cx.graph, num, den);
        Some(V::Node(node))
    }
}

fn character_is_irreducible(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, x] = a else { return None };
    let (_, _, ct) = table_of(cx, *g)?;
    let x = read_class_function(cx.graph, &ct, *x)?;
    let ip = ct.inner(&x, &x);
    Some(V::Bool((ip.re - 1.0).abs() < 1e-6 && ip.im.abs() < 1e-6))
}

fn character_decompose(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, x] = a else { return None };
    let (_, _, ct) = table_of(cx, *g)?;
    let x = read_class_function(cx.graph, &ct, *x)?;
    Some(V::ints(ct.decompose(&x)?))
}

fn class_nodes(
    cx: &Cx<'_>,
    ct: &CharTable,
    n: NodeId,
) -> Option<Vec<NodeId>> {
    let list = items(cx.graph, n)?;
    if list.len() == ct.classes.len() {
        Some(list)
    } else if list.len() == ct.n {
        Some(ct.reps.iter().map(|&r| list[r]).collect())
    } else {
        None
    }
}

fn simplified_list(
    cx: &mut Cx<'_>,
    nodes: Vec<NodeId>,
) -> V {
    V::List(nodes.into_iter().map(|x| V::Node(cx.simplify(x))).collect())
}

fn character_tensor(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, x, y] = a else { return None };
    let (_, _, ct) = table_of(cx, *g)?;
    let (x, y) = (class_nodes(cx, &ct, *x)?, class_nodes(cx, &ct, *y)?);
    let prods: Vec<NodeId> = x.iter().zip(&y).map(|(&p, &q)| prod(cx.graph, &[p, q])).collect();
    Some(simplified_list(cx, prods))
}

fn square(
    cx: &mut Cx<'_>,
    a: &[NodeId],
    sign: i64,
) -> Option<V> {
    let [g, x] = a else { return None };
    let (_, t, ct) = table_of(cx, *g)?;
    let x = class_nodes(cx, &ct, *x)?;
    let sq = ct.power_classes(&t, 2);
    let half = rat_node(cx.graph, 1, 2);
    let s = cx.graph.int(sign);
    let mut out = Vec::new();
    for i in 0..x.len() {
        let two = cx.graph.int(2);
        let chi2 = super::pow(cx.graph, x[i], two);
        let rot = prod(cx.graph, &[s, x[sq[i]]]);
        let inner = sum(cx.graph, &[chi2, rot]);
        out.push(prod(cx.graph, &[half, inner]));
    }
    Some(simplified_list(cx, out))
}

fn character_sym_square(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    square(cx, a, 1)
}

fn character_alt_square(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    square(cx, a, -1)
}

fn character_adams(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, x, k] = a else { return None };
    let k = idx(cx.graph, *k)?;
    let (_, t, ct) = table_of(cx, *g)?;
    let x = class_nodes(cx, &ct, *x)?;
    let pc = ct.power_classes(&t, k);
    Some(V::List(pc.iter().map(|&c| V::Node(x[c])).collect()))
}

fn character_conjugate(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, x] = a else { return None };
    let (_, _, ct) = table_of(cx, *g)?;
    let x = class_nodes(cx, &ct, *x)?;
    let mut out = Vec::new();
    for v in x {
        let c = apply(cx.graph, "conj", &[v])?;
        out.push(c);
    }
    Some(simplified_list(cx, out))
}

fn character_regular(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let (_, t, classes) = classes_of(cx, *a.first()?)?;
    Some(V::List(
        classes.iter().map(|c| if c[0] == t.id { V::uint(t.n) } else { V::int(0) }).collect(),
    ))
}

fn matrices(
    g: &Graph,
    n: NodeId,
) -> Option<Vec<Vec<Vec<NodeId>>>> {
    items(g, n)?.into_iter().map(|m| rows(g, m)).collect()
}

fn trace_node(
    cx: &mut Cx<'_>,
    m: &[Vec<NodeId>],
) -> Option<NodeId> {
    if m.iter().any(|r| r.len() != m.len()) {
        return None;
    }
    let diag: Vec<NodeId> = m.iter().enumerate().map(|(i, r)| r[i]).collect();
    let t = sum(cx.graph, &diag);
    Some(cx.simplify(t))
}

fn character_of_matrices(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, m] = a else { return None };
    let (_, t, classes) = classes_of(cx, *g)?;
    let mats = matrices(cx.graph, *m)?;
    if mats.len() != t.n {
        return None;
    }
    let mut out = Vec::new();
    for c in &classes {
        out.push(V::Node(trace_node(cx, &mats[c[0]])?));
    }
    Some(V::List(out))
}

fn representation_decompose(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, m] = a else { return None };
    let (_, _, ct) = table_of(cx, *g)?;
    let mats = matrices(cx.graph, *m)?;
    if mats.len() != ct.n {
        return None;
    }
    let bindings = HashMap::new();
    let mut chi = Vec::new();
    for &r in &ct.reps {
        let tr = trace_node(cx, &mats[r])?;
        chi.push(cx.graph.eval_complex(tr, &bindings)?);
    }
    Some(V::ints(ct.decompose(&chi)?))
}

fn character_projection(
    cx: &mut Cx<'_>,
    a: &[NodeId],
) -> Option<V> {
    let [g, i, m] = a else { return None };
    let (_, _, ct) = table_of(cx, *g)?;
    let i = idx(cx.graph, *i)?.checked_sub(1).filter(|&i| i < ct.rows.len())?;
    let mats = matrices(cx.graph, *m)?;
    if mats.len() != ct.n {
        return None;
    }
    let dim = mats[0].len();
    if mats.iter().any(|m| m.len() != dim || m.iter().any(|r| r.len() != dim)) {
        return None;
    }
    let coeffs: Vec<NodeId> = (0..ct.n)
        .map(|x| {
            let conj = ct.rows[i][ct.class_of[x]].conj();
            entry_node(cx.graph, &conj)
        })
        .collect();
    let scale = rat_node(cx.graph, i64::try_from(ct.degrees[i]).ok()?, i64::try_from(ct.n).ok()?);
    let mut out = Vec::new();
    for r in 0..dim {
        let mut row = Vec::new();
        for c in 0..dim {
            let terms: Vec<NodeId> = (0..ct.n).map(|x| prod(cx.graph, &[coeffs[x], mats[x][r][c]])).collect();
            let s = sum(cx.graph, &terms);
            let scaled = prod(cx.graph, &[scale, s]);
            row.push(V::Node(cx.simplify(scaled)));
        }
        out.push(V::List(row));
    }
    Some(V::List(out))
}

