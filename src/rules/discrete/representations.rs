const fn mpow(
    mut b: u64,
    mut e: u64,
    p: u64,
) -> u64 {
    let mut r = 1;
    b %= p;
    while e > 0 {
        if e & 1 == 1 {
            r = r * b % p;
        }
        b = b * b % p;
        e >>= 1;
    }
    r
}

const fn minv(
    a: u64,
    p: u64,
) -> u64 {
    mpow(a, p - 2, p)
}

fn is_prime(n: u64) -> bool {
    n >= 2 && (2..n).take_while(|d| d * d <= n).all(|d| !n.is_multiple_of(d))
}

/// The null vector of the `k x k` matrix `a` modulo `p`, if the null space is
/// one-dimensional.
fn null_vector(
    mut a: Vec<Vec<u64>>,
    p: u64,
) -> Option<Vec<u64>> {
    let k = a.len();
    let mut pivots = Vec::new();
    let mut row = 0;
    for col in 0..k {
        let Some(r) = (row..k).find(|&r| a[r][col] != 0) else { continue };
        a.swap(row, r);
        let inv = minv(a[row][col], p);
        for x in &mut a[row] {
            *x = *x * inv % p;
        }
        for r2 in 0..k {
            if r2 != row && a[r2][col] != 0 {
                let f = a[r2][col];
                for c in 0..k {
                    a[r2][c] = (a[r2][c] + p - f * a[row][c] % p) % p;
                }
            }
        }
        pivots.push(col);
        row += 1;
    }
    if pivots.len() != k - 1 {
        return None;
    }
    let free = (0..k).find(|c| !pivots.contains(c))?;
    let mut v = vec![0; k];
    v[free] = 1;
    for (r, &pc) in pivots.iter().enumerate() {
        v[pc] = (p - a[r][free]) % p;
    }
    Some(v)
}

/// The characteristic polynomial coefficients (`c[i]` of `x^i`) of a matrix
/// modulo `p` (Faddeev–LeVerrier).
fn charpoly(
    a: &[Vec<u64>],
    p: u64,
) -> Vec<u64> {
    let k = a.len();
    let mut coeffs = vec![0; k + 1];
    coeffs[k] = 1;
    let mut m = vec![vec![0_u64; k]; k];
    for i in 1..=k {
        // m = a * m + c_{k-i+1} I
        let mut next = vec![vec![0_u64; k]; k];
        for r in 0..k {
            for c in 0..k {
                let mut s = 0;
                for t in 0..k {
                    s = (s + a[r][t] * m[t][c]) % p;
                }
                next[r][c] = s;
            }
            next[r][r] = (next[r][r] + coeffs[k - i + 1]) % p;
        }
        m = next;
        // c_{k-i} = -(1/i) tr(a m)
        let mut tr = 0;
        for r in 0..k {
            for t in 0..k {
                tr = (tr + a[r][t] * m[t][r]) % p;
            }
        }
        let inv = minv(i as u64, p);
        coeffs[k - i] = (p - tr * inv % p) % p;
    }
    coeffs
}

fn eval_poly(
    c: &[u64],
    x: u64,
    p: u64,
) -> u64 {
    c.iter().rev().fold(0, |acc, &co| (acc * x + co) % p)
}

