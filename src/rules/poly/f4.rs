//! F4: the Faugère matrix algorithm for Gröbner bases.
//!
//! Pairs are selected by the *normal strategy with sugar*: the critical pair
//! of smallest degree is taken first, and all pairs of that degree are
//! processed together. Their S-polynomials, together with a reducer row for
//! every reducible monomial they contain, are collected into one **Macaulay
//! matrix**; the matrix is put into row echelon form over the coefficient
//! domain and every pivot row whose leading monomial is new is added to the
//! basis.
//! Pending pairs are kept in FIFO buckets keyed by sugar degree. Rows with a
//! fixed column layout can be prepared independently on the CPU pool.
//!
//! # Coefficient domains
//!
//! The engine runs over either the rationals or a prime field `GF(p)`
//! ([`Domain`](crate::rules::poly::field::Domain)). The domain is threaded
//! through every arithmetic kernel of [`common`] — the matrix echelon form,
//! the S-polynomial, the normal form and the final reduction — so over
//! `GF(p)` the elimination is modular: additions and multiplications are
//! reduced modulo `p` and a pivot is inverted with a modular inverse. Nothing
//! is computed over `Q` and reduced afterwards. Coefficients of a `GF(p)`
//! result are the canonical integers `0 .. p`, monic and reduced exactly like
//! the rational result.
//!
//! # Why this is still Buchberger
//!
//! Writing `S = (1/lc f) t_f f - (1/lc g) t_g g` with `L = lcm(lm f, lm g)`,
//! every monomial of both sides divides `L`, and monomial orders are
//! multiplication compatible, so every monomial of an S-polynomial is at most
//! `L`. Symbolic preprocessing closes the matrix under reduction: a monomial
//! that is divisible by a basis leading monomial gets the row `(u/lm h) h`.
//! Consequently the normal form of an S-polynomial *inside the matrix* only
//! ever subtracts pivot rows whose leading monomial is a monomial of the
//! polynomial being reduced — i.e. at most `L`. Reading the echelon rows back
//! as polynomials therefore expresses the S-polynomial as a combination of
//! basis elements and new rows in which every term is at most `L`. That is
//! exactly a standard representation, which is what Buchberger's criterion
//! (and its product and chain refinements) need; no pair is lost.
//!
//! # Linear algebra
//!
//! Elimination is sparse Gaussian elimination over the coefficient domain with
//! [`BigRational`] coefficients: over `Q` the exact choice, not a modular or
//! floating-point one; over `GF(p)` the same exact algorithm where every
//! addition and multiplication is reduced modulo `p` and every division is a
//! modular inverse. Each pivot row is normalised to a unit pivot coefficient
//! and subtracted from every later row that hits its column. The row space —
//! hence the ideal generated by the polynomials read back from the rows — is
//! preserved exactly. Every pivot row is then reduced modulo the current basis
//! (the standard "tail reduction" of F4), and every non-zero result is added
//! to the basis with its leading monomial un-covered, which grows the leading
//! ideal and guarantees termination.
//!
//! Limits on the number of matrices, rows, columns, pairs, reductions and
//! basis elements turn a runaway computation into an unevaluated request
//! (`Outcome::Pass`) instead of a wrong or truncated answer.
//!
//! The final [`common::reduced_basis`] step makes the result the unique
//! reduced basis for the order, so it is literally the same list as
//! [`crate::rules::poly::groebner::groebner`] returns — and over `GF(p)`,
//! literally the same list as [`crate::rules::poly::groebner::groebner_in`].

