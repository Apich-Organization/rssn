    #[test]
    fn f4_output_is_the_reduced_basis() {
        let order = Order::GradedRevLex;
        let generators = cyclic(4, order);
        let basis = f4_basis(&generators, order, F4Limits::default()).unwrap_or_default();
        // Monic, and no term of an element is reducible by another element:
        // that is the definition of a fully reduced basis.
        for g in &basis {
            assert_eq!(g.leading().map(|(_, c)| c), Some(&q(1)));
            let others: Vec<GPoly> = basis.iter().filter(|h| h != &g).cloned().collect();
            for (monomial, _) in g.terms() {
                for other in &others {
                    if let Some((lead, _)) = other.leading() {
                        assert!(
                            !common::divides(lead, monomial),
                            "a term of a basis element is reducible by another element"
                        );
                    }
                }
            }
        }
        // Minimal: no leading monomial divides another.
        let leads: Vec<&Vec<u32>> = basis
            .iter()
            .filter_map(|g| g.leading().map(|(m, _)| m))
            .collect();
        for (i, a) in leads.iter().enumerate() {
            for (j, b) in leads.iter().enumerate() {
                if i != j {
                    assert!(!common::divides(a, b), "the basis is not minimal");
                }
            }
        }
        for generator in &generators {
            assert!(normal_form(&Domain::Rational, generator, &basis, order).is_zero());
        }
        // Idempotent: Buchberger on the basis changes nothing.
        assert_eq!(
            groebner(&basis, order, GroebnerLimits::default()).as_deref(),
            Some(basis.as_slice())
        );
    }

