//! F4: the Faugère matrix algorithm for Gröbner bases.
//!
//! Pairs are selected by the *normal strategy with sugar*: the critical pair
//! of smallest degree is taken first, and all pairs of that degree are
//! processed together. Their S-polynomials, together with a reducer row for
//! every reducible monomial they contain, are collected into one **Macaulay
//! matrix**; the matrix is put into row echelon form over `Q` and every pivot
//! row whose leading monomial is new is added to the basis.
//!
//! # Why this is still Buchberger
//!
//! Writing `S = (1/lc f) t_f f - (1/lc g) t_g g` with `L = lcm(lm f, lm g)`,
//! every monomial of both sides divides `L`, and monomial orders are
//! multiplication compatible, so every monomial of an S-polynomial is at most
//! `L`. Symbolic preprocessing closes the matrix under reduction: a monomial
//! that is divisible by a basis leading monomial gets the row `(u/lm h) h`.
//! Consequently the normal form of an S-polynomial *inside the matrix* only
//! ever subtracts pivot rows whose leading monomial is a monomial of the
//! polynomial being reduced — i.e. at most `L`. Reading the echelon rows back
//! as polynomials therefore expresses the S-polynomial as a combination of
//! basis elements and new rows in which every term is at most `L`. That is
//! exactly a standard representation, which is what Buchberger's criterion
//! (and its product and chain refinements) need; no pair is lost.
//!
//! # Linear algebra
//!
//! Elimination is sparse Gaussian elimination over `Q` with [`BigRational`]
//! coefficients: the exact choice, not a modular or floating-point one. Each
//! pivot row is normalised to a unit pivot coefficient and subtracted from
//! every later row that hits its column. The row space — hence the ideal
//! generated by the polynomials read back from the rows — is preserved
//! exactly. Every pivot row is then reduced modulo the current basis (the
//! standard "tail reduction" of F4), and every non-zero result is added to
//! the basis with its leading monomial un-covered, which grows the leading
//! ideal and guarantees termination.
//!
//! Limits on the number of matrices, rows, columns, pairs, reductions and
//! basis elements turn a runaway computation into an unevaluated request
//! (`Outcome::Pass`) instead of a wrong or truncated answer.
//!
//! The final [`common::reduced_basis`] step makes the result the unique
//! reduced basis for the order, so it is literally the same list as
//! [`crate::rules::poly::groebner::groebner`] returns.

// The phases of one algorithm: pair handling, matrix construction,
// elimination and installation. They are private to this module and each
// serves exactly one step of the loop.
