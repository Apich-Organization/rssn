//! # Numerical Integral Transforms
//!
//! The discrete Fourier transform of `n` complex samples in the
//! `X_k = sum_j x_j exp(-2 pi i j k / n)` convention, in place:
//!
//! * [`fft`] / [`ifft`] on a `Vec`, keeping its length;
//! * [`fft_slice`] / [`ifft_slice`] on a slice, for row/column passes;
//! * [`fft_many_par`] / [`ifft_many_par`] on a batch of rows, transformed
//!   concurrently but bit-identically to the serial calls;
//! * [`rfft`] / [`irfft`] for real input, returning the `n/2 + 1` non-redundant
//!   bins.
//!
//! **Power-of-two lengths** take the iterative radix-2 Cooley-Tukey kernel
//! ([`fft_cooley_tukey_in_place`]) directly on the buffer: `log2(n)` stages of
//! `n/2` butterflies, no allocation.
//!
//! **Prime lengths** take Rader's transform: `X_0` is the sample sum, the
//! multiplicative group modulo `p = n` is generated by a primitive root `g`, and
//! `X_{g^m} = x_0 + sum_c x_{g^c} omega^{g^{c+m}}`, a cyclic convolution of
//! length `p - 1` that is evaluated with three radix-2 transforms of
//! `m = next_power_of_two(2p - 3)` points. The twiddles use the exact integer
//! exponents `g^{+-t} mod p`, so Rader has no chirp phase error; and because its
//! convolution is sized from `2p - 3` rather than `2p`, primes of the form
//! `2^(k-1) + 1` (`17`, `257`, `65537`) need half the points Bluestein would
//! (`257` uses `512`, not `1024`).
//!
//! **Every other length** takes Bluestein's chirp-z algorithm. With
//! `w_j = exp(-i pi j^2 / n)` and `jk = (j^2 + k^2 - (k - j)^2) / 2`,
//!
//! ```text
//! X_k = w_k * sum_j (x_j w_j) conj(w_{k-j}),
//! ```
//!
//! which is a linear convolution of length `2n - 1`, evaluated by zero-padding
//! to `m = next_power_of_two(2n)` and using three radix-2 transforms of size
//! `m`. Only the first `n` outputs of that convolution are kept, so the result
//! is the `n`-point DFT itself — the padding is internal to the convolution and
//! never reaches the caller, who sees `n` coefficients for `n` samples.
//!
//! **Real input** uses [`rfft`] / [`irfft`], the standard real-to-complex
//! packing: an even `n = 2m` is packed into the `m` complex values
//! `z_j = x_{2j} + i x_{2j+1}`, one `m`-point complex transform is taken, and
//! the `m + 1` non-redundant bins `X_k = E_k + W_n^k O_k` are unpacked from
//! `Z_k` and `conj(Z_{m-k})`. Odd `n` has no such packing and falls back to one
//! full `n`-point complex transform, keeping the first `n/2 + 1` bins. The
//! return convention matches [`fft`] / [`ifft`]: [`rfft`] is unnormalised and
//! its half spectrum has length `n/2 + 1`, [`irfft`] divides by `n`.
//!
//! ## Limitations
//!
//! Length is no longer a restriction: every `n >= 1` is a true `n`-point
//! transform, `ifft(fft(x)) = x` at every length, and the returned vector has
//! the same length as the input. What remains true:
//!
//! * **Cost.** A power-of-two `n` costs `log2(n)` stages of `n/2` butterflies.
//!   A prime `n` costs three transforms of `m' = next_power_of_two(2n - 3)`,
//!   which is at most the Bluestein size and half of it for `n = 2^(k-1) + 1`.
//!   A composite `n` still costs three transforms of the next power of two
//!   `m >= 2n`, i.e. `3 m log2(m)` butterfly stages against `n log2(n)` for the
//!   power-of-two path of the same length — about `6.6x` at `n = 1000`
//!   (`m = 2048`) — plus two `O(m)` scratch buffers. There is no mixed-radix
//!   prime-factor algorithm for composite lengths.
//! * **No odd-length real packing.** [`rfft`] halves the work for even `n` only;
//!   an odd `n` runs a full complex transform (Rader for a prime, Bluestein
//!   otherwise) and copies the first `n/2 + 1` bins.
//! * **One transform is single-threaded.** A single call is serial: the radix-2
//!   stages, Rader and Bluestein all run on one thread. Independent transforms
//!   can be threaded with [`fft_many_par`] / [`ifft_many_par`] (bit-identical to
//!   the serial calls) or by the caller with the slice variants; threading
//!   inside one transform (a parallel batched radix-2 or a split-radix stage
//!   scheduler) is not implemented.
//! * **Normalisation.** [`fft`] and [`rfft`] are unnormalised; [`ifft`] and
//!   [`irfft`] divide by `n` (`irfft` divides by the target length, not by the
//!   half-spectrum length).
//! * **Accuracy.** Accumulation is `f64`. The round trip and Parseval hold to
//!   about `1e-14 * n` relative. Rader's twiddle phases are exact rational
//!   multiples of `2 pi`; Bluestein adds an `O(eps * n)` chirp-phase error on
//!   top of the radix-2 round-off.

use std::f64::consts::PI;

use num_complex::Complex;
use num_complex::Complex64;

/// The optimized, in-place, iterative Cooley-Tukey Fast Fourier Transform (FFT) algorithm.
///
/// This function operates directly on the slice, avoiding memory allocations and copies.
/// It assumes the input slice length is a power of two; other lengths are
/// handled by the public wrappers through Bluestein's algorithm.
///
/// # Arguments
/// * `data` - A mutable slice of `Complex<f64>` representing the input sequence.
pub(crate) fn fft_cooley_tukey_in_place(data: &mut [Complex<f64>]) {
    let n = data.len();

    if n <= 1 {
        return;
    }

    let mut j = 0;

    for i in 0..n {
        if i < j {
            data.swap(i, j);
        }

        let mut bit = n >> 1;

        while j & bit != 0 {
            j ^= bit;

            bit >>= 1;
        }

        j ^= bit;
    }

    let mut len = 2;

    while len <= n {
        let half_len = len / 2;

        let w_m = Complex::from_polar(1.0, -2.0 * PI / (len as f64));

        for i in (0..n).step_by(len) {
            let mut w = Complex::new(1.0, 0.0);

            for k in 0..half_len {
                let even_idx = i + k;

                let odd_idx = i + k + half_len;

                let t = w * data[odd_idx];

                let u = data[even_idx];

                data[even_idx] = u + t;

                data[odd_idx] = u - t;

                w *= w_m;
            }
        }

        len *= 2;
    }
}

/// The inverse radix-2 transform: `conj(fft(conj(x))) / n`, in place.
///
/// The input length must be a power of two.
fn inverse_pow2_in_place(data: &mut [Complex<f64>]) {
    for val in data.iter_mut() {
        *val = val.conj();
    }

    fft_cooley_tukey_in_place(data);

    let n_f64 = data.len() as f64;

    for val in data.iter_mut() {
        *val = val.conj() / n_f64;
    }
}

/// Bluestein's chirp-z transform of an arbitrary length, returning `n` samples.
///
/// `X_k = w_k * sum_j (x_j w_j) conj(w_{k-j})` with `w_j = exp(-i pi j^2 / n)`;
/// the sum is a linear convolution of length `2n - 1` done cyclically at
/// `m = next_power_of_two(2n)`, where no wrap-around can reach the first `n`
/// outputs. The chirp angle uses `j^2 mod 2n`, so the phase stays exact for
/// `j` up to the square root of the machine word.
fn bluestein_forward(data: &[Complex<f64>]) -> Vec<Complex<f64>> {
    let n = data.len();

    let two_n = n.saturating_mul(2);

    let chirp: Vec<Complex<f64>> = (0..n)
        .map(|j| {
            let jj = j.wrapping_mul(j) % two_n;

            Complex::from_polar(1.0, -PI * (jj as f64) / (n as f64))
        })
        .collect();

    let m = two_n.next_power_of_two();

    let mut fa: Vec<Complex<f64>> = data.iter().zip(chirp.iter()).map(|(x, w)| x * w).collect();

    fa.resize(m, Complex::new(0.0, 0.0));

    // b_d = conj(w_d) and b is even in d, so the mirror image fills m - d.
    let mut fb: Vec<Complex<f64>> = (0..m)
        .map(|p| {
            let d = p.min(m.saturating_sub(p));

            chirp.get(d).map_or(Complex::new(0.0, 0.0), Complex::conj)
        })
        .collect();

    fft_cooley_tukey_in_place(&mut fa);

    fft_cooley_tukey_in_place(&mut fb);

    for (a, b) in fa.iter_mut().zip(fb.iter()) {
        *a *= *b;
    }

    inverse_pow2_in_place(&mut fa);

    fa.iter().zip(chirp.iter()).map(|(c, w)| c * w).collect()
}

/// Trial-division primality test; exact for every `usize`.
const fn is_prime(n: usize) -> bool {
    if n < 2 {
        return false;
    }
    if n.is_multiple_of(2) {
        return n == 2;
    }
    let mut divisor = 3;
    while divisor <= n / divisor {
        if n.is_multiple_of(divisor) {
            return false;
        }
        divisor += 2;
    }
    true
}

/// `a * b mod m`, without overflowing `usize`.
const fn mul_mod(
    a: usize,
    b: usize,
    m: usize,
) -> usize {
    ((a as u128 * b as u128) % m as u128) as usize
}

/// `base^exponent mod m`.
const fn pow_mod(
    mut base: usize,
    mut exponent: usize,
    m: usize,
) -> usize {
    let mut result = 1;
    base %= m;
    while exponent > 0 {
        if exponent & 1 == 1 {
            result = mul_mod(result, base, m);
        }
        base = mul_mod(base, base, m);
        exponent >>= 1;
    }
    result
}

/// A primitive root modulo the prime `p`, or `None` when `p` has none.
///
/// The multiplicative group of a prime is cyclic; a candidate is rejected when
/// `candidate^((p-1)/q) = 1` for a prime factor `q` of `p - 1`.
fn primitive_root(p: usize) -> Option<usize> {
    if p == 2 {
        return Some(1);
    }
    if p < 2 {
        return None;
    }
    let mut remainder = p - 1;
    let mut factor = 2;
    let mut prime_factors = Vec::new();
    while factor <= remainder / factor {
        if remainder.is_multiple_of(factor) {
            prime_factors.push(factor);
            while remainder.is_multiple_of(factor) {
                remainder /= factor;
            }
        }
        factor += 1;
    }
    if remainder > 1 {
        prime_factors.push(remainder);
    }
    'candidate: for candidate in 2..p {
        for &prime in &prime_factors {
            if pow_mod(candidate, (p - 1) / prime, p) == 1 {
                continue 'candidate;
            }
        }
        return Some(candidate);
    }
    None
}

/// The convolution length Rader's algorithm needs for a prime `p`: at least
/// `2(p - 1) - 1` points, rounded up to a power of two.
///
/// Bluestein's chirp-z transform of the same length needs a power of two above
/// `2p`, so for `p = 2^(k-1) + 1` (17, 257, 65537) the Rader convolution is
/// exactly half the size: `p = 257` uses 512 points instead of 1024.
const fn rader_convolution_length(p: usize) -> usize {
    (2 * p - 3).next_power_of_two()
}

/// Rader's prime-length forward transform.
///
/// `X_0` is the sum of the samples. Writing `g` for a primitive root,
/// `X_{g^m} = x_0 + sum_c x_{g^c} omega^{g^{c+m}}`, and with `b_c = x_{g^c}`
/// and `c_t = omega^{g^{-t}}` that sum is the cyclic convolution of `b` and `c`
/// read at `-m`: `X_{g^m} = x_0 + (b * c)[-m]`. The length-`p-1` cyclic
/// convolution is evaluated by zero-padding to `rader_convolution_length(p)`
/// and using one radix-2 forward pair and one inverse transform. The padded
/// product is the *linear* convolution, so the cyclic value at `s` folds the
/// tail at `s + (p - 1)` back in. Every twiddle uses the exact integer exponent
/// `g^{+-t} mod p`, so unlike the chirp-z path there is no phase error from
/// reducing `j^2` into a float angle.
fn rader_forward(data: &[Complex<f64>]) -> Vec<Complex<f64>> {
    let p = data.len();
    let mut out = vec![Complex::new(0.0, 0.0); p];
    out[0] = data.iter().copied().sum();
    if p == 2 {
        out[1] = data[0] - data[1];
        return out;
    }
    let Some(generator) = primitive_root(p) else {
        // Unreachable when the caller has established that `p` is prime.
        return bluestein_forward(data);
    };
    let len = p - 1;
    let mut powers = Vec::with_capacity(len);
    let mut value = 1;
    for _ in 0..len {
        powers.push(value);
        value = mul_mod(value, generator, p);
    }
    let mut signal: Vec<Complex<f64>> = powers.iter().map(|&index| data[index]).collect();
    let mut kernel: Vec<Complex<f64>> = (0..len)
        .map(|offset| {
            // powers[(len - offset) % len] = g^{-offset} mod p.
            let exponent = powers[(len - offset) % len];
            Complex::from_polar(1.0, -2.0 * PI * (exponent as f64) / (p as f64))
        })
        .collect();
    let m = rader_convolution_length(p);
    signal.resize(m, Complex::new(0.0, 0.0));
    kernel.resize(m, Complex::new(0.0, 0.0));
    fft_cooley_tukey_in_place(&mut signal);
    fft_cooley_tukey_in_place(&mut kernel);
    for (left, right) in signal.iter_mut().zip(&kernel) {
        *left *= *right;
    }
    inverse_pow2_in_place(&mut signal);
    for (offset, &index) in powers.iter().enumerate() {
        // The zero-padded product is the *linear* convolution; the length-`len`
        // cyclic value at `s` folds its wrap-around tail from `s + len`.
        let index_cyclic = (len - offset) % len;
        let low = signal.get(index_cyclic).copied().unwrap_or_default();
        let high = signal.get(index_cyclic + len).copied().unwrap_or_default();
        out[index] = data[0] + low + high;
    }
    out
}

/// The forward transform of a length that is not a power of two: Rader for a
/// prime length, Bluestein's chirp-z transform otherwise.
fn forward_any(data: &[Complex<f64>]) -> Vec<Complex<f64>> {
    if is_prime(data.len()) {
        rader_forward(data)
    } else {
        bluestein_forward(data)
    }
}

/// The inverse transform, in place, for every length.
fn inverse_any_in_place(data: &mut [Complex<f64>]) {
    let n = data.len();
    if n.is_power_of_two() {
        inverse_pow2_in_place(data);

        return;
    }
    let conjugated: Vec<Complex<f64>> = data.iter().map(Complex::conj).collect();
    let transformed = forward_any(&conjugated);
    let n_f64 = n as f64;
    for (value, out) in data.iter_mut().zip(transformed.iter()) {
        *value = out.conj() / n_f64;
    }
}
/// Computes the Fast Fourier Transform (FFT) of a sequence of complex numbers.
///
/// Works at any length and leaves the length unchanged: a power-of-two `n` uses
/// the in-place radix-2 kernel, a prime `n` uses Rader's transform, and any
/// other `n` uses Bluestein's chirp-z algorithm. Either way the result is the
/// exact `n`-point DFT, `O(n log n)`.
///
/// # Arguments
/// * `data` - A mutable `Vec<Complex<f64>>` representing the input sequence.
///
/// # Example
/// ```rust
/// use num_complex::Complex;
/// use rssn::kernels::transforms::fft;
///
/// let mut data = vec![
///     Complex::new(1.0, 0.0),
///     Complex::new(1.0, 0.0),
///     Complex::new(0.0, 0.0),
///     Complex::new(0.0, 0.0),
/// ];
///
/// fft(&mut data);
///
/// assert!((data[0].re - 2.0).abs() < 1e-9);
/// ```
///
/// A length that is not a power of two keeps its length:
/// ```rust
/// use num_complex::Complex;
/// use rssn::kernels::transforms::fft;
///
/// let mut data = vec![Complex::new(1.0, 0.0); 3];
///
/// fft(&mut data);
///
/// assert_eq!(data.len(), 3);
/// // [3, 0, 0] for a constant signal.
/// assert!((data[0].re - 3.0).abs() < 1e-12);
/// ```
pub fn fft(data: &mut [Complex<f64>]) {
    let n = data.len();

    if n <= 1 {
        return;
    }

    if n.is_power_of_two() {
        fft_cooley_tukey_in_place(data);
    } else {
        data.copy_from_slice(&forward_any(data));
    }
}

/// Computes the Inverse Fast Fourier Transform (IFFT).
///
/// Works at any length and leaves the length unchanged, so `ifft(fft(x))`
/// returns `x` at every length. The `1/n` normalisation is included.
///
/// # Arguments
/// * `data` - A mutable `Vec<Complex<f64>>` representing the input frequency-domain sequence.
///
/// # Example
/// ```rust
/// use num_complex::Complex;
/// use rssn::kernels::transforms::fft;
/// use rssn::kernels::transforms::ifft;
///
/// let mut data = vec![Complex::new(1.0, 2.0), Complex::new(3.0, 4.0)];
///
/// let original = data.clone();
///
/// fft(&mut data);
///
/// ifft(&mut data);
///
/// assert!((data[0].re - original[0].re).abs() < 1e-9);
///
/// assert!((data[0].im - original[0].im).abs() < 1e-9);
/// ```
pub fn ifft(data: &mut [Complex<f64>]) {
    let n = data.len();

    if n <= 1 {
        return;
    }

    inverse_any_in_place(data);
}

/// Computes the real-input FFT: the `n/2 + 1` non-redundant bins of the DFT of
/// a real sequence.
///
/// For real `x`, the full spectrum obeys `X_{n-k} = conj(X_k)`, so only the
/// bins `k = 0 ..= n/2` are returned (length `n/2 + 1`, unnormalised like
/// [`fft`]). At even `n = 2m` the sequence is packed as the `m` complex values
/// `x_{2j} + i x_{2j+1}`, so one `m`-point complex transform replaces the
/// `n`-point one. Odd `n` has no such packing and runs a full `n`-point complex
/// transform, keeping the first `n/2 + 1` bins.
///
/// # Arguments
/// * `x` - The real input sequence.
///
/// # Example
/// ```rust
/// use rssn::kernels::transforms::rfft;
///
/// // An impulse has a flat half spectrum.
/// let spectrum = rfft(&[1.0, 0.0, 0.0, 0.0]);
///
/// assert_eq!(spectrum.len(), 3);
/// assert!((spectrum[0].re - 1.0).abs() < 1e-12);
/// assert!((spectrum[2].re - 1.0).abs() < 1e-12);
/// ```
///
/// A constant signal concentrates all the energy in the DC bin:
/// ```rust
/// use rssn::kernels::transforms::rfft;
///
/// let spectrum = rfft(&[2.0; 5]);
///
/// assert!((spectrum[0].re - 10.0).abs() < 1e-12);
/// assert!(spectrum[1..].iter().all(|bin| bin.norm() < 1e-12));
/// ```
#[must_use]
pub fn rfft(x: &[f64]) -> Vec<Complex64> {
    let n = x.len();

    if n == 0 {
        return Vec::new();
    }

    if n == 1 {
        return vec![Complex64::new(x[0], 0.0)];
    }

    if n.is_multiple_of(2) {
        let m = n / 2;

        let mut packed: Vec<Complex64> = x
            .as_chunks::<2>()
            .0
            .iter()
            .map(|pair| Complex64::new(pair[0], pair[1]))
            .collect();

        fft(&mut packed);

        let n_f64 = n as f64;

        let mut spectrum = Vec::with_capacity(m + 1);

        for k in 0..=m {
            // Z_{m} = Z_{0} by periodicity, so index m with 0.
            let z_k = packed[k % m];

            let conj_z_mk = packed[(m - k % m) % m].conj();

            let even = (z_k + conj_z_mk) * 0.5;

            let odd = Complex64::new(0.0, -0.5) * (z_k - conj_z_mk);

            let twiddle = Complex64::from_polar(1.0, -2.0 * PI * (k as f64) / n_f64);

            spectrum.push(even + twiddle * odd);
        }

        spectrum
    } else {
        let mut full: Vec<Complex64> = x.iter().map(|&value| Complex64::new(value, 0.0)).collect();

        fft(&mut full);

        full.truncate(n / 2 + 1);

        full
    }
}

/// Inverts [`rfft`]: reconstructs the real signal of length `n` from its
/// `n/2 + 1` non-redundant bins, with the `1/n` normalisation of [`ifft`].
///
/// The imaginary parts of the DC bin (`k = 0`) and, for even `n`, of the
/// Nyquist bin (`k = n/2`) are ignored, because a real signal has purely real
/// values there. Even `n = 2m` is unpacked into one `m`-point inverse complex
/// transform; odd `n` reconstructs the full conjugate-symmetric spectrum and
/// takes one `n`-point inverse transform.
///
/// Returns an empty vector when `n` is zero or when `spectrum.len()` is not
/// `n/2 + 1`.
///
/// # Arguments
/// * `spectrum` - The half spectrum produced by [`rfft`] (or any conjugate-
///   symmetric data).
/// * `n` - The length of the reconstructed real signal.
///
/// # Example
/// ```rust
/// use rssn::kernels::transforms::irfft;
/// use rssn::kernels::transforms::rfft;
///
/// let x = [0.5, -1.25, 2.0, 0.0, -3.5, 1.0];
/// let back = irfft(&rfft(&x), x.len());
///
/// for (got, want) in back.iter().zip(x) {
///     assert!((got - want).abs() < 1e-12);
/// }
/// ```
#[must_use]
pub fn irfft(
    spectrum: &[Complex64],
    n: usize,
) -> Vec<f64> {
    if n == 0 || spectrum.len() != n / 2 + 1 {
        return Vec::new();
    }

    if n == 1 {
        return vec![spectrum[0].re];
    }

    if n.is_multiple_of(2) {
        let m = n / 2;

        let n_f64 = n as f64;

        let dc = spectrum[0].re;

        let nyquist = spectrum[m].re;

        let mut packed = Vec::with_capacity(m);

        for k in 0..m {
            let x_k = if k == 0 {
                Complex64::new(dc, 0.0)
            } else {
                spectrum[k]
            };

            let conj_x_mk = if k == 0 {
                Complex64::new(nyquist, 0.0)
            } else {
                spectrum[m - k].conj()
            };

            let even = (x_k + conj_x_mk) * 0.5;

            // O_k = (X_k - conj(X_{m-k})) / (2 W_n^k), and Z_k = E_k + i O_k.
            let inv_twiddle = Complex64::from_polar(1.0, 2.0 * PI * (k as f64) / n_f64);

            let odd = (x_k - conj_x_mk) * 0.5 * inv_twiddle;

            packed.push(even + Complex64::new(0.0, 1.0) * odd);
        }

        ifft(&mut packed);

        let mut x = Vec::with_capacity(n);

        for value in packed {
            x.push(value.re);
            x.push(value.im);
        }

        x
    } else {
        let half = n / 2;

        let mut full = vec![Complex64::new(0.0, 0.0); n];

        full[0] = Complex64::new(spectrum[0].re, 0.0);

        for k in 1..=half {
            full[k] = spectrum[k];
            full[n - k] = spectrum[k].conj();
        }

        ifft(&mut full);

        full.iter().map(|value| value.re).collect()
    }
}

/// Computes the Forward FFT for a slice.
///
/// **Use this for efficient, parallel chunk processing (e.g., with rayon).**
/// Works at any length and operates in place: a power-of-two length uses the
/// radix-2 kernel, a prime length Rader's transform, and any other length
/// Bluestein's algorithm. Bit-identical to [`fft`].
///
/// # Arguments
/// * `data` - A mutable slice of `Complex<f64>` representing the input sequence.
///
/// # Example
/// ```rust
/// use num_complex::Complex;
/// use rssn::kernels::transforms::fft_slice;
///
/// let mut data = vec![
///     Complex::new(1.0, 0.0),
///     Complex::new(1.0, 0.0),
///     Complex::new(0.0, 0.0),
///     Complex::new(0.0, 0.0),
/// ];
///
/// fft_slice(&mut data);
///
/// assert!((data[0].re - 2.0).abs() < 1e-9);
/// ```
pub fn fft_slice(data: &mut [Complex<f64>]) {
    fft(data);
}

/// Computes the Inverse FFT for a slice.
///
/// **Use this for efficient, parallel chunk processing (e.g., with rayon).**
/// Works at any length and operates in place; the `1/n` normalisation is
/// included. Bit-identical to [`ifft`].
///
/// # Arguments
/// * `data` - A mutable slice of `Complex<f64>` representing the input frequency-domain sequence.
///
/// # Example
/// ```rust
/// use num_complex::Complex;
/// use rssn::kernels::transforms::fft_slice;
/// use rssn::kernels::transforms::ifft_slice;
///
/// let mut data = vec![Complex::new(1.0, 0.0), Complex::new(0.0, 0.0)];
///
/// let original = data.clone();
///
/// fft_slice(&mut data);
///
/// ifft_slice(&mut data);
///
/// assert!((data[0].re - original[0].re).abs() < 1e-9);
/// ```
pub fn ifft_slice(data: &mut [Complex<f64>]) {
    ifft(data);
}

/// Forward FFT of every row, concurrently, in row order.
///
/// Each row runs the serial [`fft`] kernel and only different rows run
/// concurrently, so the result is bit-identical to transforming the rows one at
/// a time and therefore independent of the thread count. Fewer than `grain`
/// rows (or `grain < 2`) run sequentially, so a small batch does not pay for the
/// task spawn. Use the batch entry point instead of a hand-written `rayon` map
/// when the rows are independent (the usual row/column pass of a 2-D transform).
#[must_use]
pub fn fft_many_par(
    rows: &[Vec<Complex<f64>>],
    grain: usize,
) -> Vec<Vec<Complex<f64>>> {
    crate::kernels::par::map_slice(rows, grain, |row| {
        let mut buffer = row.clone();
        fft(&mut buffer);
        buffer
    })
}

/// [`fft_many_par`] for the inverse transform.
#[must_use]
pub fn ifft_many_par(
    rows: &[Vec<Complex<f64>>],
    grain: usize,
) -> Vec<Vec<Complex<f64>>> {
    crate::kernels::par::map_slice(rows, grain, |row| {
        let mut buffer = row.clone();
        ifft(&mut buffer);
        buffer
    })
}

#[cfg(test)]
mod primes_tests {
    //! Rader's prime-length path: the exact `n`-point transform against the
    //! direct DFT, the convolution-size saving over Bluestein, the accuracy of
    //! both chirp-free and chirp paths, and the public dispatch at lengths too
    //! large for an `O(n^2)` oracle.

    #![allow(clippy::indexing_slicing, clippy::arithmetic_side_effects)]
    #![allow(clippy::single_call_fn)]

    use super::*;

    /// Naive `O(n^2)` DFT, the reference every fast path is checked against.
    fn direct_dft(x: &[Complex<f64>]) -> Vec<Complex<f64>> {
        let n = x.len();
        (0..n)
            .map(|k| {
                x.iter()
                    .enumerate()
                    .fold(Complex::new(0.0, 0.0), |acc, (j, xj)| {
                        let angle = -2.0 * PI * (j as f64) * (k as f64) / (n as f64);
                        acc + xj * Complex::from_polar(1.0, angle)
                    })
            })
            .collect()
    }

    /// A deterministic complex signal with both parts of order one.
    fn sample(n: usize) -> Vec<Complex<f64>> {
        (0..n)
            .map(|i| {
                let t = i as f64;
                Complex::new((0.3 * t).sin() + 0.5, (0.7 * t).cos() - 0.2)
            })
            .collect()
    }

    fn primes_up_to(limit: usize) -> Vec<usize> {
        (2..=limit).filter(|&n| is_prime(n)).collect()
    }

    fn max_error(
        got: &[Complex<f64>],
        want: &[Complex<f64>],
    ) -> f64 {
        got.iter()
            .zip(want)
            .map(|(g, w)| (g - w).norm())
            .fold(0.0, f64::max)
    }

    #[test]
    fn rader_matches_the_direct_dft_at_every_small_prime() {
        let primes = primes_up_to(257);
        assert!(primes.len() > 50, "{} primes", primes.len());
        for p in primes {
            let x = sample(p);
            let want = direct_dft(&x);
            let got = rader_forward(&x);
            assert_eq!(got.len(), p);
            let scale = want.iter().map(|c| c.norm()).fold(1.0_f64, f64::max);
            for (bin, (g, w)) in got.iter().zip(&want).enumerate() {
                assert!(
                    (g - w).norm() <= 1e-12 * scale,
                    "p = {p}, bin {bin}: {g} vs {w}"
                );
            }
        }
    }

    #[test]
    fn rader_convolution_is_at_most_the_bluestein_size() {
        // `2^(k-1) + 1` primes get an exact factor two.
        for p in [17usize, 257] {
            assert_eq!(
                rader_convolution_length(p) * 2,
                (2 * p).next_power_of_two(),
                "p = {p}"
            );
        }
        for p in primes_up_to(1021) {
            assert!(
                rader_convolution_length(p) <= (2 * p).next_power_of_two(),
                "p = {p}"
            );
        }
    }

    #[test]
    fn rader_and_bluestein_are_both_accurate_at_prime_lengths() {
        for p in [17usize, 257, 1021] {
            let x = sample(p);
            let want = direct_dft(&x);
            let scale = want.iter().map(|c| c.norm()).fold(1.0_f64, f64::max);
            let rader_error = max_error(&rader_forward(&x), &want) / scale;
            let bluestein_error = max_error(&bluestein_forward(&x), &want) / scale;
            println!(
                "p = {p}: Rader relative error {rader_error:.3e}, \
                 Bluestein {bluestein_error:.3e}"
            );
            assert!(
                rader_error <= 1e-12,
                "Rader error at p = {p}: {rader_error}"
            );
            assert!(
                bluestein_error <= 1e-12,
                "Bluestein error at p = {p}: {bluestein_error}"
            );
        }
    }

    #[test]
    fn the_public_transform_dispatches_to_rader_and_round_trips() {
        for p in [257usize, 1021, 4099] {
            let x = sample(p);
            let via_dispatch = forward_any(&x);
            let via_rader = rader_forward(&x);
            for (bin, (a, b)) in via_dispatch.iter().zip(&via_rader).enumerate() {
                assert_eq!(
                    a.re.to_bits(),
                    b.re.to_bits(),
                    "dispatch re at p = {p}, bin {bin}"
                );
                assert_eq!(
                    a.im.to_bits(),
                    b.im.to_bits(),
                    "dispatch im at p = {p}, bin {bin}"
                );
            }
            let mut data = x.clone();
            fft(&mut data);
            assert!(data.iter().all(|c| c.re.is_finite() && c.im.is_finite()));
            ifft(&mut data);
            // The round-tripped round-off grows like `eps * n` (two transforms
            // and the `1/n` scaling at a few thousand points).
            let tolerance = 4.0 * f64::EPSILON * p as f64;
            for (got, want) in data.iter().zip(&x) {
                assert!(
                    (got - want).norm() <= tolerance * want.norm().max(1.0),
                    "round trip at p = {p}: {got} vs {want}"
                );
            }
        }
    }
}
