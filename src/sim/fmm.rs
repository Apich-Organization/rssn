//! # Adaptive fast multipole methods in two and three dimensions
//!
//! Both solvers evaluate the Gauss-law field `E(x_i) = sum_j s_j (x_j - x_i) / r^D`
//! (`1/r` in 2-D, `1/r^2` in 3-D) in `O(N)` operations for bounded order `p`.
//!
//! * [`fmm3d`] is a 3-D FMM on an **adaptive octree** (leaves are split until
//!   they hold at most `leaf_size` points, so clustered distributions give
//!   deep, sparse trees). Expansions are Cartesian Taylor series of `1/r` up to
//!   total degree `p`: particle-to-multipole (P2M), multipole-to-multipole
//!   (M2M), multipole-to-local (M2L), local-to-local (L2L) and local
//!   evaluation, with derivative tensors of `1/r` generated by the exact
//!   Laplace recurrence. The interaction lists come from a dual-tree
//!   traversal with the multipole acceptance criterion
//!   `r_A + r_B <= theta |c_A - c_B|` (tight bounding radii), so the work adapts
//!   to the tree, and the error is controlled by `p` and `theta`.
//! * [`fmm2d`] is the 2-D analogue (complex-variable expansions of the
//!   logarithmic potential, M2M/M2L/L2L) on an adaptive quadtree.
//!
//! Plummer softening `eps` is applied **consistently** to the near field and to the
//! expansions: the multipole-to-local translation uses the derivative tensors of the
//! softened kernel `(|x|^2 + eps^2)^(-1/2)`, so the result converges to the direct softened sum.
//!
//! * [`periodic_fmm3d`] is the **periodic** 3-D FMM for a general triclinic cell: the central cell
//!   and its `(2w+1)^3 - 1` nearest images are treated by the tree code and the remaining lattice
//!   by the Taylor expansion of the Ewald-regularised lattice potential (tinfoil boundary
//!   conditions, neutralising background), whose derivative tensors are built from the Ewald
//!   splitting with incomplete-gamma derivatives of the screened kernel.
//!
//! The far lattice is softened consistently too: the Plummer sphere's form factor `k eps K_1(k eps)`
//! multiplies the reciprocal lattice sum, the regular self part is integrated numerically, and the
//! explicitly treated near images are subtracted with the softened kernel
//! ([`PeriodicFmmOptions::soften_far`]); the (exponentially small) screened real-space tail is not softened.
//!
//! Limitations: the 2-D solver is open-boundary only; P3M (particle-particle,
//! particle-mesh) is not implemented, [`crate::sim::ewald::pme_reciprocal_cell`] covers the
//! mesh route for Coulomb systems.


/// Parameters of an FMM evaluation.
#[derive(Clone, Copy, Debug)]
pub struct FmmOptions {
    /// Expansion order `p` (total degree in 3-D, number of terms in 2-D).
    pub order: usize,
    /// Maximum number of points in a leaf box.
    pub leaf_size: usize,
    /// Multipole acceptance parameter: boxes interact through expansions when
    /// `r_A + r_B <= theta * distance`.
    pub theta: f64,
    /// Plummer softening applied to near-field interactions.
    pub eps: f64,
}

impl Default for FmmOptions {
    fn default() -> Self {
        Self { order: 6, leaf_size: 24, theta: 0.5, eps: 0.0 }
    }
}

const MAX_DEPTH: usize = 40;

#[derive(Clone, Debug)]
struct TNode<const D: usize> {
    center: [f64; D],
    half: f64,
    rad: f64,
    start: usize,
    end: usize,
    children: Vec<usize>,
}

#[derive(Clone, Debug)]
struct Tree<const D: usize> {
    nodes: Vec<TNode<D>>,
    perm: Vec<usize>,
}

fn build_tree<const D: usize>(
    pos: &[[f64; D]],
    leaf_size: usize,
) -> Tree<D> {
    let mut lo = [f64::INFINITY; D];
    let mut hi = [f64::NEG_INFINITY; D];
    for p in pos {
        for a in 0..D {
            lo[a] = lo[a].min(p[a]);
            hi[a] = hi[a].max(p[a]);
        }
    }
    let mut center = [0.0; D];
    let mut half = 0.0_f64;
    for a in 0..D {
        center[a] = f64::midpoint(lo[a], hi[a]);
        half = half.max(0.5 * (hi[a] - lo[a]));
    }
    half = half * 1.000_001 + 1e-12;
    let mut tree = Tree { nodes: Vec::new(), perm: (0..pos.len()).collect() };
    split_node(&mut tree, pos, (0, pos.len()), (center, half), 0, leaf_size.max(1));
    tree
}

fn split_node<const D: usize>(
    tree: &mut Tree<D>,
    pos: &[[f64; D]],
    range: (usize, usize),
    geom: ([f64; D], f64),
    depth: usize,
    leaf_size: usize,
) -> usize {
    let (start, end) = range;
    let (center, half) = geom;
    let id = tree.nodes.len();
    let mut rad = 0.0_f64;
    for &i in &tree.perm[start..end] {
        let mut r2 = 0.0;
        for a in 0..D {
            r2 += (pos[i][a] - center[a]).powi(2);
        }
        rad = rad.max(r2.sqrt());
    }
    tree.nodes.push(TNode { center, half, rad, start, end, children: Vec::new() });
    if end - start <= leaf_size || depth >= MAX_DEPTH {
        return id;
    }
    let nb = 1usize << D;
    let mut buckets: Vec<Vec<usize>> = vec![Vec::new(); nb];
    for &i in &tree.perm[start..end] {
        let mut o = 0;
        for a in 0..D {
            if pos[i][a] >= center[a] {
                o |= 1 << a;
            }
        }
        buckets[o].push(i);
    }
    let mut at = start;
    let mut ranges = Vec::new();
    for (o, b) in buckets.iter().enumerate() {
        if b.is_empty() {
            continue;
        }
        for (k, &i) in b.iter().enumerate() {
            tree.perm[at + k] = i;
        }
        ranges.push((o, at, at + b.len()));
        at += b.len();
    }
    let hh = half * 0.5;
    let mut kids = Vec::new();
    for (o, s, e) in ranges {
        let mut c = center;
        for a in 0..D {
            c[a] += if (o >> a) & 1 == 1 { hh } else { -hh };
        }
        kids.push(split_node(tree, pos, (s, e), (c, hh), depth + 1, leaf_size));
    }
    tree.nodes[id].children = kids;
    id
}

/// Dual-tree traversal: calls `far(target, source)` for well-separated node
/// pairs and `near(target, source)` for leaf pairs that must be summed directly.
fn traverse<const D: usize>(
    tree: &Tree<D>,
    theta: f64,
    mut far: impl FnMut(usize, usize),
    mut near: impl FnMut(usize, usize),
) {
    let mut stack = vec![(0usize, 0usize)];
    while let Some((a, b)) = stack.pop() {
        let (na, nb) = (&tree.nodes[a], &tree.nodes[b]);
        let a_leaf = na.children.is_empty();
        let b_leaf = nb.children.is_empty();
        if a != b {
            let mut d2 = 0.0;
            for k in 0..D {
                d2 += (na.center[k] - nb.center[k]).powi(2);
            }
            if na.rad + nb.rad <= theta * d2.sqrt() {
                far(a, b);
                continue;
            }
        }
        if a_leaf && b_leaf {
            near(a, b);
        } else if a == b {
            for &ca in &na.children {
                for &cb in &na.children {
                    stack.push((ca, cb));
                }
            }
        } else if a_leaf || (!b_leaf && nb.half >= na.half) {
            for &cb in &nb.children {
                stack.push((a, cb));
            }
        } else {
            for &ca in &na.children {
                stack.push((ca, b));
            }
        }
    }
}

// ---------------------------------------------------------------------------
// 3-D: Cartesian Taylor expansions of 1/r
// ---------------------------------------------------------------------------

struct Tables3 {
    p: usize,
    q: usize,
    list: Vec<[usize; 3]>,
    idx: Vec<usize>,
    nc: usize,
    fact: Vec<f64>,
    sum_idx: Vec<usize>,
}

impl Tables3 {
    fn new(p: usize) -> Self {
        let q = 2 * p;
        let mut list = Vec::new();
        for n in 0..=q {
            for a in (0..=n).rev() {
                for b in (0..=(n - a)).rev() {
                    list.push([a, b, n - a - b]);
                }
            }
        }
        let w = q + 1;
        let mut idx = vec![usize::MAX; w * w * w];
        for (i, k) in list.iter().enumerate() {
            idx[(k[0] * w + k[1]) * w + k[2]] = i;
        }
        let nc = (p + 1) * (p + 2) * (p + 3) / 6;
        let mut fact = vec![1.0; q + 2];
        for i in 1..q + 2 {
            fact[i] = fact[i - 1] * i as f64;
        }
        let mut t = Self { p, q, list, idx, nc, fact, sum_idx: Vec::new() };
        let mut si = vec![0; nc * nc];
        for g in 0..nc {
            for a in 0..nc {
                let (kg, ka) = (t.list[g], t.list[a]);
                si[g * nc + a] = t.at([kg[0] + ka[0], kg[1] + ka[1], kg[2] + ka[2]]);
            }
        }
        t.sum_idx = si;
        t
    }

    fn at(
        &self,
        k: [usize; 3],
    ) -> usize {
        let w = self.q + 1;
        self.idx[(k[0] * w + k[1]) * w + k[2]]
    }

    fn fact3(
        &self,
        k: &[usize; 3],
    ) -> f64 {
        self.fact[k[0]] * self.fact[k[1]] * self.fact[k[2]]
    }

    /// Derivatives `D^k (q^(-1/2))` at `x`, `q = |x|^2 + eps2`, for all `|k| <= 2p`
    /// (`eps2 = 0`: the Coulomb kernel; `eps2 > 0`: the Plummer-softened kernel, for which the
    /// same Leibniz recurrence holds because `q` is a quadratic polynomial of `x`).
    fn derivs(
        &self,
        x: [f64; 3],
        eps2: f64,
        out: &mut Vec<f64>,
    ) {
        let r2 = x[0] * x[0] + x[1] * x[1] + x[2] * x[2] + eps2;
        out.clear();
        out.resize(self.list.len(), 0.0);
        out[0] = 1.0 / r2.sqrt();
        for i in 1..self.list.len() {
            let k = self.list[i];
            let ax = if k[0] > 0 {
                0
            } else if k[1] > 0 {
                1
            } else {
                2
            };
            let mut kp = k;
            kp[ax] -= 1;
            let mut s = -x[ax] * out[self.at(kp)];
            if kp[ax] > 0 {
                let mut k2 = kp;
                k2[ax] -= 1;
                s -= kp[ax] as f64 * out[self.at(k2)];
            }
            for j in 0..3 {
                if kp[j] > 0 {
                    let mut kj = k;
                    kj[j] -= 1;
                    s -= 2.0 * kp[j] as f64 * x[j] * out[self.at(kj)];
                    if kp[j] > 1 {
                        let mut kjj = k;
                        kjj[j] -= 2;
                        s -= (kp[j] * (kp[j] - 1)) as f64 * out[self.at(kjj)];
                    }
                }
            }
            out[i] = s / r2;
        }
    }

    /// Monomials `y^k / k!` (or plain `y^k`) for `|k| <= p`.
    fn monomials(
        &self,
        y: [f64; 3],
        scaled: bool,
    ) -> Vec<f64> {
        let p = self.p;
        let pw = |v: f64| -> Vec<f64> {
            let mut o = vec![1.0; p + 1];
            for i in 1..=p {
                o[i] = o[i - 1] * v;
            }
            o
        };
        let (px, py, pz) = (pw(y[0]), pw(y[1]), pw(y[2]));
        (0..self.nc)
            .map(|i| {
                let k = self.list[i];
                let m = px[k[0]] * py[k[1]] * pz[k[2]];
                if scaled {
                    m / self.fact3(&k)
                } else {
                    m
                }
            })
            .collect()
    }
}

/// Result of a 3-D FMM evaluation.
#[derive(Clone, Debug)]
pub struct Fmm3Result {
    /// Potential `sum_j s_j / r_ij` (softened near field), self excluded.
    pub potential: Vec<f64>,
    /// Field `sum_j s_j (x_j - x_i) / r_ij^3`, self excluded.
    pub field: Vec<[f64; 3]>,
}

fn sub3(
    a: &[f64; 3],
    b: &[f64; 3],
) -> [f64; 3] {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}

/// Adaptive 3-D FMM for the potential `sum s_j / r` and its gradient field.
///
/// # Errors
/// Fails for empty input, length mismatch or `theta` outside `(0, 1)`.
pub fn fmm3d(
    pos: &[[f64; 3]],
    src: &[f64],
    opts: &FmmOptions,
) -> Result<Fmm3Result, String> {
    let n = pos.len();
    if n == 0 || src.len() != n {
        return Err("positions and sources must be non-empty and of equal length".into());
    }
    if !(opts.theta > 0.0 && opts.theta < 1.0) {
        return Err("theta must lie in (0, 1)".into());
    }
    let t = Tables3::new(opts.order);
    let tree = build_tree::<3>(pos, opts.leaf_size);
    let nn = tree.nodes.len();
    let nc = t.nc;
    let mut mp = vec![0.0; nn * nc];
    let mut lo = vec![0.0; nn * nc];
    // P2M
    for (id, nd) in tree.nodes.iter().enumerate() {
        if !nd.children.is_empty() {
            continue;
        }
        for &i in &tree.perm[nd.start..nd.end] {
            let m = t.monomials(sub3(&pos[i], &nd.center), true);
            for a in 0..nc {
                mp[id * nc + a] += src[i] * m[a];
            }
        }
    }
    // M2M (children are created after their parents)
    for id in (0..nn).rev() {
        let nd = &tree.nodes[id];
        for &c in &nd.children {
            let m = t.monomials(sub3(&tree.nodes[c].center, &nd.center), true);
            for a in 0..nc {
                let ka = t.list[a];
                let mut s = 0.0;
                for b in 0..nc {
                    let kb = t.list[b];
                    if kb[0] <= ka[0] && kb[1] <= ka[1] && kb[2] <= ka[2] {
                        s += mp[c * nc + b] * m[t.at([ka[0] - kb[0], ka[1] - kb[1], ka[2] - kb[2]])];
                    }
                }
                mp[id * nc + a] += s;
            }
        }
    }
    let mut pot = vec![0.0; n];
    let mut fld = vec![[0.0; 3]; n];
    let eps2 = opts.eps * opts.eps;
    let mut m2l_list: Vec<(usize, usize)> = Vec::new();
    traverse(
        &tree,
        opts.theta,
        |a, b| m2l_list.push((a, b)),
        |a, b| {
            let (na, nb) = (&tree.nodes[a], &tree.nodes[b]);
            for &i in &tree.perm[na.start..na.end] {
                for &j in &tree.perm[nb.start..nb.end] {
                    if i == j {
                        continue;
                    }
                    let d = sub3(&pos[j], &pos[i]);
                    let r2 = d[0] * d[0] + d[1] * d[1] + d[2] * d[2] + eps2;
                    let ir = 1.0 / r2.sqrt();
                    let ir3 = ir / r2;
                    pot[i] += src[j] * ir;
                    for k in 0..3 {
                        fld[i][k] += src[j] * d[k] * ir3;
                    }
                }
            }
        },
    );
    // M2L
    let mut dbuf = Vec::new();
    let parity: Vec<f64> = t.list.iter().map(|k| if (k[0] + k[1] + k[2]) % 2 == 0 { 1.0 } else { -1.0 }).collect();
    for (a, b) in m2l_list {
        let x = sub3(&tree.nodes[a].center, &tree.nodes[b].center);
        t.derivs(x, eps2, &mut dbuf);
        for g in 0..nc {
            let mut s = 0.0;
            for al in 0..nc {
                s += parity[al] * mp[b * nc + al] * dbuf[t.sum_idx[g * nc + al]];
            }
            lo[a * nc + g] += s / t.fact3(&t.list[g]);
        }
    }
    // L2L (parents before children)
    for id in 0..nn {
        let nd = &tree.nodes[id];
        for &c in &nd.children {
            let m = t.monomials(sub3(&tree.nodes[c].center, &nd.center), true);
            for g in 0..nc {
                let kg = t.list[g];
                let mut s = 0.0;
                for b in 0..nc {
                    let kb = t.list[b];
                    if kb[0] >= kg[0] && kb[1] >= kg[1] && kb[2] >= kg[2] {
                        s += t.fact3(&kb) * lo[id * nc + b] * m[t.at([kb[0] - kg[0], kb[1] - kg[1], kb[2] - kg[2]])];
                    }
                }
                lo[c * nc + g] += s / t.fact3(&kg);
            }
        }
    }
    // L2P
    for (id, nd) in tree.nodes.iter().enumerate() {
        if !nd.children.is_empty() {
            continue;
        }
        for &i in &tree.perm[nd.start..nd.end] {
            let m = t.monomials(sub3(&pos[i], &nd.center), false);
            for g in 0..nc {
                let l = lo[id * nc + g];
                let kg = t.list[g];
                pot[i] += l * m[g];
                for ax in 0..3 {
                    if kg[ax] > 0 {
                        let mut kk = kg;
                        kk[ax] -= 1;
                        fld[i][ax] += kg[ax] as f64 * l * m[t.at(kk)];
                    }
                }
            }
        }
    }
    Ok(Fmm3Result { potential: pot, field: fld })
}

