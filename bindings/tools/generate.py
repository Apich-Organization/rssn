def emit_julia_base_ext(api: dict) -> str:
    lines = [
        f"# {BANNER}",
        "#",
        "# `Term` methods on Base functions, so `sin(x)`, `sqrt(x)` and `diff(f, x)`",
        "# read naturally. A name that Base already exports is not re-exported by",
        "# RSSN (that would make `using RSSN` ambiguous), so this is how the common",
        "# mathematical operators reach unqualified call sites.",
        "",
    ]
    present = {op["name"] for op in api["ops"]}
    functions = jl_base_functions()
    for name in JL_BASE_EXTENSIONS:
        if name not in present or (functions and name not in functions):
            continue
        if name == "log":
            # `Base.log(x)` is the natural logarithm, which the engine spells
            # `ln`, and `Base.log(b, x)` takes the base first, as the engine's
            # `log(b, x)` does. The blanket `(a, rest...)` form would send a
            # one-argument `log(x)` to the engine's two-argument operator.
            lines += [
                'Base.log(x::Term) = _apply("ln", (x,), nothing)',
                'Base.log(b::Term, x::Term) = _apply("log", (b, x), nothing)',
                'Base.log(b::Term, x::Real) = _apply("log", (b, x), nothing)',
                'Base.log(b::Real, x::Term) = _apply("log", (b, x), nothing)',
            ]
            continue
        lines.append(
            f'Base.{name}(a::Term, rest...) = _apply("{name}", (a, rest...), nothing)'
        )
    return "\n".join(lines) + "\n"


def emit_julia_exports(api: dict) -> str:
    # A base-extension operator has no module-local function to export; the rest
    # are exported under their (possibly mangled) binding name.
    names = [jl_name(op["name"]) for op in api["ops"] if op["name"] not in JL_BASE_EXTENSIONS]
    names = sorted(set(names))
    lines = [
        f"# {BANNER}",
        "#",
        "# Every operator whose name `Base` does not already export. The rest stay",
        "# reachable as `RSSN.sin(x)` (and as `sin(x)` through `base_ext.jl`).",
        "",
        "export",
    ]
    width = 92
    row: list[str] = []
    for name in names:
        row.append(name)
        if sum(len(entry) + 2 for entry in row) > width:
            lines.append("    " + ", ".join(row[:-1]) + ",")
            row = [name]
    if row:
        lines.append("    " + ", ".join(row))
    return "\n".join(lines) + "\n"


