def py_name(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) else name


def jl_name(name: str) -> str:
    """The Julia binding name for an operator.

    A name is suffixed when it is a keyword, when the hand-written API already
    uses it, or when `Base` exports it and the operator is *not* one we extend
    `Base` with — defining `collect` or `pi` inside the module would shadow
    `Base` for every line of the module itself.
    """
    if name in JL_KEYWORDS or name in JL_RESERVED:
        return name + "_"
    if name in jl_base_names() and name not in JL_BASE_EXTENSIONS:
        return name + "_"
    return name


def cpp_name(name: str) -> str:
    return name + "_op" if name in CPP_KEYWORDS or name in CPP_RESERVED else name


def _clean_doc(text: str) -> str:
    text = " ".join(text.split())
    return text.replace("\\", "\\\\")


def _julia_doc(text: str) -> str:
    """Doc text safe inside a Julia triple-quoted string: `$` interpolates."""
    return _clean_doc(text).replace("$", "\\$")


def _arity_text(op: dict) -> str:
    minimum, maximum = op["arity_min"], op["arity_max"]
    if maximum is None:
        return f"{minimum}+ args"
    if minimum == maximum:
        return f"{minimum} args"
    return f"{minimum}..{maximum} args"


def _doc_block(lines: list[str], op: dict, comment: str) -> list[str]:
    out = list(lines)
    if op["eval"] == "host_callback":
        out.append(
            "Returns a dynamic value: this operator is higher-order, its function "
            "parameters are host callbacks, and a callable passed for one is "
            "registered with the signature the operator declares."
        )
    else:
        out.append(
            f"Returns an unevaluated term; call ``Session.compute`` to reduce it."
            if comment == "#"
            else "Returns an unevaluated term; call `compute` to reduce it."
        )
    if not op["ffi"]:
        out.append(
            "Not callable through the C ABI: the manifest marks this operator "
            "`backend_support.ffi = false` because it is generic over dimension "
            "parameters, which a C host cannot instantiate. Call it from Rust."
        )
    return out


