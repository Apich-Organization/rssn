def emit_julia_ops(api: dict) -> str:
    lines = [
        f"# {BANNER}",
        "",
        "#: Operator name => (min arity, max arity or `nothing`, ffi reachable).",
        "const OPS = Dict{String, Tuple{Int, Union{Int, Nothing}, Bool}}(",
    ]
    for op in api["ops"]:
        maximum = "nothing" if op["arity_max"] is None else str(op["arity_max"])
        lines.append(f'    "{op["name"]}" => ({op["arity_min"]}, {maximum}, {str(op["ffi"]).lower()}),')
    lines += [")", "", "#: Operator name => the Julia binding name.", "const NAMES = Dict{String, String}("]
    for op in api["ops"]:
        lines.append(f'    "{op["name"]}" => "{jl_name(op["name"])}",')
    lines += [")", "", "#: Operators grouped by rule set.", "const BY_RULE_SET = Dict{String, Vector{String}}("]
    by_rule: dict[str, list[str]] = {}
    for op in api["ops"]:
        by_rule.setdefault(op["rule_set"], []).append(jl_name(op["name"]))
    for key in sorted(by_rule):
        entries = ", ".join(f'"{entry}"' for entry in sorted(by_rule[key]))
        lines.append(f'    "{key}" => [{entries}],')
    lines += [")", "", "#: Operators grouped by manifest category.", "const BY_CATEGORY = Dict{String, Vector{String}}("]
    by_category: dict[str, list[str]] = {}
    for op in api["ops"]:
        by_category.setdefault(op["category"] or "uncategorised", []).append(jl_name(op["name"]))
    for key in sorted(by_category):
        entries = ", ".join(f'"{entry}"' for entry in sorted(by_category[key]))
        lines.append(f'    "{key}" => [{entries}],')
    lines += [")", ""]
    # The documentation of every operator, in one place: the docstring of each
    # function interpolates its entry, so `?diff` and `op_help("diff")` read the
    # same text and the file carries it once.
    lines += ["#: Operator name => the engine's own documentation.",
              "const OPERATOR_DOCS = Dict{String, String}("]
    for op in api["ops"]:
        doc = _julia_doc(op["doc"])
        extra = (
            "Returns a dynamic value: this operator is higher-order, its function "
            "parameters are host callbacks, and a callable passed for one is "
            "registered with the signature the operator declares."
            if op["eval"] == "host_callback"
            else "Returns an unevaluated term; call `compute` to reduce it."
        )
        if _checked_value(op):
            extra += " Pass `checked=true` to call it with native arguments and receive a Value."
        lines.append(
            f'    "{op["name"]}" => "{doc}{BACKSLASH}n{BACKSLASH}n{extra}",'
        )
    lines += [")", ""]

    for op in api["ops"]:
        if op["name"] in JL_BASE_EXTENSIONS:
            # Emitted as a `Base` method in `base_ext.jl` instead.
            continue
        name = jl_name(op["name"])
        caller = "_call" if op["eval"] == "host_callback" else "_apply"
        checked = _checked_value(op)
        keyword_option = ", checked = false" if checked else ""
        if checked:
            caller = "(checked ? _call : _apply)"
        doc = '    $(OPERATOR_DOCS["' + op["name"] + '"])'

        if op["arity_max"] is None:
            lines.append(
                f'"""\n{doc}\n"""\n{name}(args...; session = nothing{keyword_option}) = '
                f'{caller}("{op["name"]}", args, session)\n'
            )
        elif op["arity_max"] == 0:
            lines.append(
                f'"""\n{doc}\n"""\n{name}(; session = nothing{keyword_option}) = '
                f'{caller}("{op["name"]}", (), session)\n'
            )
        else:
            reserved = JL_KEYWORDS | ({"checked"} if checked else set())
            names = param_names(op, "a", reserved)
            params = ", ".join(names)
            passed = ", ".join(names)
            tuple_text = f"({passed},)" if op["arity_max"] == 1 else f"({passed})"
            lines.append(
                f'"""\n{doc}\n"""\n{name}({params}; session = nothing{keyword_option}) = '
                f'{caller}("{op["name"]}", {tuple_text}, session)\n'
            )

    for op in api["ops"]:
        if op["name"] in JL_BASE_EXTENSIONS:
            continue
        for alias in op["aliases"]:
            if alias in {entry["name"] for entry in api["ops"]}:
                continue
            lines.append(f'const {jl_name(alias)} = {jl_name(op["name"])}\n')
    return "\n".join(lines) + "\n"


