def py_name(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) else name


def jl_name(name: str) -> str:
    """The Julia binding name for an operator.

    A name is suffixed when it is a keyword, when the hand-written API already
    uses it, or when `Base` exports it and the operator is *not* one we extend
    `Base` with — defining `collect` or `pi` inside the module would shadow
    `Base` for every line of the module itself.
    """
    if name in JL_KEYWORDS or name in JL_RESERVED:
        return name + "_"
    if name in jl_base_names() and name not in JL_BASE_EXTENSIONS:
        return name + "_"
    return name


def r_name(name: str) -> str:
    """The R binding name for an operator: `rssn_` and the operator's own name.

    The prefix is what keeps generated functions out of base R's way:
    `rssn_diff()` rather than `diff`. Every operator name in the manifest is
    already a valid R identifier.
    """
    return f"rssn_{name}"


def cpp_name(name: str) -> str:
    return name + "_op" if name in CPP_KEYWORDS or name in CPP_RESERVED else name


def documented_params(op: dict) -> list[str] | None:
    """The parameter names the operator's documentation states, or `None`.

    About a fifth of the operators spell their signature out
    (`` `bicgstab_l_solve(a, b, tol)`: ... ``). Using those names is what makes
    a generated function's arguments self-describing. Anything unusual -- a
    token that is not an identifier (`basis[coords]`), a repeated name, a count
    that disagrees with the declared arity -- gives `None`, and the caller falls
    back to positional names.
    """
    match = DOC_SIGNATURE.match(op.get("doc") or "")
    if not match:
        return None
    tokens = [token.strip() for token in match.group(2).split(",") if token.strip()]
    if not tokens or len(tokens) != op["arity_max"]:
        return None
    if any(not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", token) for token in tokens):
        return None
    if len(set(tokens)) != len(tokens):
        return None
    return tokens


def param_names(op: dict, prefix: str, reserved: set[str], mangler=None) -> list[str]:
    """The parameter names of the generated function for `op`.

    `prefix` is what a fallback name starts with (`a` gives `a0`, `a1`, ...).
    """
    maximum = op["arity_max"]
    if maximum is None:
        return []
    documented = documented_params(op)
    if documented is None:
        return [f"{prefix}{index}" for index in range(maximum)]
    names: list[str] = []
    for token in documented:
        name = mangler(token) if mangler is not None else token
        if name in reserved or name in PARAM_RESERVED:
            return [f"{prefix}{index}" for index in range(maximum)]
        names.append(name)
    return names


def _clean_doc(text: str) -> str:
    text = " ".join(text.split())
    return text.replace("\\", "\\\\")


def _julia_doc(text: str) -> str:
    """Doc text safe inside a Julia string literal.

    `\\` and `"` are escaped so the text can live in a `"..."` literal, and `$`
    so a doc that mentions a price or a shell variable is not interpolated.
    """
    return (
        _clean_doc(text)
        .replace(BACKSLASH, BACKSLASH + BACKSLASH)
        .replace('"', BACKSLASH + '"')
        .replace("$", BACKSLASH + "$")
    )


def _first_sentence(text: str, limit: int = 160) -> str:
    """The first sentence of a doc string, for a one-line comment."""
    cleaned = " ".join(text.split())
    match = re.search(r"(?<=[.!?])\s", cleaned)
    if match and match.start() < limit:
        return cleaned[: match.start()]
    if len(cleaned) <= limit:
        return cleaned
    return cleaned[: limit - 1].rstrip() + "…"


def _arity_text(op: dict) -> str:
    minimum, maximum = op["arity_min"], op["arity_max"]
    if maximum is None:
        return f"{minimum}+ args"
    if minimum == maximum:
        return f"{minimum} args"
    return f"{minimum}..{maximum} args"


def _signature_text(op: dict) -> str:
    """`diff(f, x)`, from the documentation when it states one."""
    documented = documented_params(op)
    if documented is not None:
        return f"{op['name']}({', '.join(documented)})"
    maximum = op["arity_max"]
    if maximum is None:
        return f"{op['name']}(...)"
    if maximum == 0:
        return f"{op['name']}()"
    return f"{op['name']}({', '.join(f'a{index}' for index in range(maximum))})"



def _checked_value(op: dict) -> bool:
    """Whether the facade can opt in to a checked call with native values."""
    return op["eval"] == "dynamic" and op["ffi"]


def _doc_block(lines: list[str], op: dict, comment: str) -> list[str]:
    out = list(lines)
    if op["eval"] == "host_callback":
        out.append(
            "Returns a dynamic value: this operator is higher-order, its function "
            "parameters are host callbacks, and a callable passed for one is "
            "registered with the signature the operator declares."
        )
    else:
        out.append(
            f"Returns an unevaluated term; call ``Session.compute`` to reduce it."
            if comment == "#"
            else "Returns an unevaluated term; call `compute` to reduce it."
        )
    if _checked_value(op):
        out.append("Pass ``checked=True`` to call it with native arguments and receive a Value.")
    if not op["ffi"]:
        out.append(
            "Not callable through the C ABI: the manifest marks this operator "
            "`backend_support.ffi = false` because it is generic over dimension "
            "parameters, which a C host cannot instantiate. Call it from Rust."
        )
    return out


