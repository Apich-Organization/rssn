def _r_wrapped(values: list[str], indent: str, width: int = 92) -> str:
    """`values` joined by commas, wrapped to `width`, with no trailing comma.

    R rejects a trailing comma inside `c()` and `list()`, so the separator has
    to be between the values, never after the last one.
    """
    rows: list[str] = []
    row: list[str] = []
    used = 0
    limit = max(width - len(indent), 24)
    for value in values:
        if row and used + len(value) + 2 > limit:
            rows.append(", ".join(row))
            row = []
            used = 0
        row.append(value)
        used += len(value) + 2
    if row:
        rows.append(", ".join(row))
    return (",\n" + indent).join(rows)


