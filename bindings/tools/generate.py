#!/usr/bin/env python3
"""Generate the language-specific tables and operator facades.

Input: `bindings/api/rssn_api.json` (see `extract_api.py`).
Output: files marked "generated" in `bindings/python`, `bindings/julia` and
`bindings/cpp`. Everything else in those trees is hand-written.

    python bindings/tools/generate.py
    python bindings/tools/generate.py --check   # exit 1 when a file is stale

The operator facade is one function per registered operator, so a caller never
has to spell an operator name as a string. Names that are keywords in a target
language are mangled (`and` -> `and_` in Python, `and_op` in C++) and the
original spelling stays reachable through `OPS` / `apply`.
"""

