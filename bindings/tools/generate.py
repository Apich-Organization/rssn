def emit_cpp_ops(api: dict) -> str:
    lines = [
        f"// {BANNER}",
        "//",
        "// One function per registered operator. Include it after `rssn/client.hpp`:",
        "//",
        '//     #include "rssn/client.hpp"',
        '//     #include "rssn/ops.hpp"',
        "//",
        "// A name that is a C++ keyword, or that the client already uses (`apply`), is",
        "// mangled with an `_op` suffix (`and_op`, `apply_op`);",
        "// `op_spec` still looks the original spelling up.",
        "",
        "#ifndef RSSN_CLIENT_OPS_HPP",
        "#define RSSN_CLIENT_OPS_HPP",
        "",
        "#include <algorithm>",
        "#include <cstring>",
        "#include <initializer_list>",
        "#include <iterator>",
        "#include <utility>",
        "",
        '#include "rssn/client.hpp"',
        '#include "rssn/value.hpp"',
        "",
        "namespace rssn {",
        "namespace client {",
        "",
        "/// Operator name, arity and reachability.",
        "struct OpSpec {",
        "    const char* name;",
        "    int min_arity;",
        "    int max_arity;  // -1 for a variadic operator",
        "    bool ffi;       // true for every operator: terms, values and callbacks all cross",
        "};",
        "",
        "/// Every registered operator, sorted by name.",
        "inline constexpr OpSpec kOps[] = {",
    ]
    for op in api["ops"]:
        maximum = -1 if op["arity_max"] is None else op["arity_max"]
        lines.append(
            f'    {{"{op["name"]}", {op["arity_min"]}, {maximum}, {str(op["ffi"]).lower()}}},'
        )
    lines += [
        "};",
        "",
        "/// The spec of `name`, or nullptr when the name is not registered.",
        "inline const OpSpec* op_spec(const char* name) {",
        "    const OpSpec* begin = std::begin(kOps);",
        "    const OpSpec* end = std::end(kOps);",
        "    const OpSpec* found = std::lower_bound(",
        "        begin, end, name,",
        "        [](const OpSpec& spec, const char* key) { return std::strcmp(spec.name, key) < 0; });",
        "    return (found != end && std::strcmp(found->name, name) == 0) ? found : nullptr;",
        "}",
        "",
    ]

    def doc_comment(op: dict) -> str:
        text = f"/// {_clean_doc(op['doc'])}"
        if op["eval"] == "host_callback":
            text += (
                "\n///\n/// Higher-order: the function parameters are host callbacks."
                "\n/// Pass a `Callback` (see `rssn/callback.hpp`) or a `Value` for each"
                "\n/// one; the result is a `Value`, not a `Term`."
            )
        elif not op["ffi"]:
            text += (
                "\n///\n/// Not callable through the C ABI: the manifest marks this operator"
                "\n/// `backend_support.ffi = false` (generic over dimension parameters)."
            )
        return text

    for op in api["ops"]:
        name = cpp_name(op["name"])
        maximum = op["arity_max"]
        lines.append(doc_comment(op))
        if op["eval"] == "host_callback":
            # A higher-order operator is reachable only through the value ABI:
            # it is the one whose arguments may be host callbacks.
            lines.append(
                "template <class... Args>\n"
                f"inline Value {name}(Args&&... args) {{\n"
                f'    return detail::call_inferred("{op["name"]}",\n'
                "                                 std::forward<Args>(args)...);\n"
                "}\n"
            )
            continue
        if maximum is None:
            lines.append(
                "template <class... Args>\n"
                f"inline Term {name}(Args&&... args) {{\n"
                "    if constexpr (sizeof...(Args) == 0) {\n"
                f'        return apply("{op["name"]}", nullptr, 0);\n'
                "    } else {\n"
                "        Term list[] = {Term(std::forward<Args>(args))...};\n"
                f'        return apply("{op["name"]}", list, sizeof...(Args));\n'
                "    }\n"
                "}\n"
            )
        elif maximum == 0:
            lines.append(f'inline Term {name}() {{ return apply("{op["name"]}", nullptr, 0); }}\n')
        else:
            params = ", ".join(f"const Term& a{index}" for index in range(maximum))
            names = ", ".join(f"a{index}" for index in range(maximum))
            lines.append(
                f"inline Term {name}({params}) {{\n"
                f"    Term args[] = {{{names}}};\n"
                f'    return apply("{op["name"]}", args, {maximum});\n'
                "}\n"
            )

    for op in api["ops"]:
        for alias in op["aliases"]:
            if alias in {entry["name"] for entry in api["ops"]}:
                continue
            target = cpp_name(op["name"])
            alias_name = cpp_name(alias)
            lines.append(f"/// Alias of `{target}`.")
            if op["arity_max"] is None:
                lines.append(
                    "template <class... Args>\n"
                    f"inline Term {alias_name}(Args&&... args) "
                    f"{{ return {target}(std::forward<Args>(args)...); }}\n"
                )
            elif op["arity_max"] == 0:
                lines.append(f"inline Term {alias_name}() {{ return {target}(); }}\n")
            else:
                params = ", ".join(f"const Term& a{index}" for index in range(op["arity_max"]))
                names = ", ".join(f"a{index}" for index in range(op["arity_max"]))
                lines.append(f"inline Term {alias_name}({params}) {{ return {target}({names}); }}\n")

    lines += [
        "// Checked dynamic operators accept native arguments in an explicit session.",
        "// They use the value ABI and preserve its typed errors.",
        "namespace checked {",
        "",
    ]
    for op in api["ops"]:
        if not _checked_value(op):
            continue
        name = cpp_name(op["name"])
        lines.append(
            "template <class... Args>\n"
            f"inline Value {name}(const Session& session, Args&&... args) {{\n"
            f'    return session.call_value("{op["name"]}", std::forward<Args>(args)...);\n'
            "}\n"
        )
    lines += ["}  // namespace checked", "", "}  // namespace client", "}  // namespace rssn",
              "", "#endif  // RSSN_CLIENT_OPS_HPP", ""]
    return "\n".join(lines)


def emit_cpp_units(api: dict) -> str:
    aliases: list[tuple[str, str]] = []
    for unit in api["units"]:
        for alias in unit["aliases"]:
            aliases.append((alias, unit["name"]))

    lines = [
        f"// {BANNER}",
        "",
        "#ifndef RSSN_CLIENT_UNITS_HPP",
        "#define RSSN_CLIENT_UNITS_HPP",
        "",
        "#include <cstring>",
        "",
        '#include "rssn/client.hpp"',
        "",
        "namespace rssn {",
        "namespace client {",
        "",
        "/// A unit of the engine's table. The scale is the exact rational",
        "/// `numer / denom * pi^pi` relative to the base unit; `offset_*` is the",
        "/// affine offset of `degC` and friends (`nullptr` when there is none).",
        "struct UnitDef {",
        "    const char* name;",
        "    const char* display;",
        "    const char* dimension;",
        "    const char* numer;",
        "    const char* denom;",
        "    int pi;",
        "    const char* offset_numer;",
        "    const char* offset_denom;",
        "    bool affine;",
        "    bool prefixable;",
        "    const char* category;",
        "    const char* since;",
        "};",
        "",
        "/// Every unit of the engine's table, sorted by name.",
        "inline constexpr UnitDef kUnits[] = {",
    ]
    for unit in api["units"]:
        offset = unit["offset"]
        on = "nullptr" if offset is None else f'"{offset["numer"]}"'
        od = "nullptr" if offset is None else f'"{offset["denom"]}"'
        lines.append(
            f'    {{"{unit["name"]}", "{unit["display"]}", "{unit["dimension"]}", '
            f'"{unit["scale"]["numer"]}", "{unit["scale"]["denom"]}", {unit["scale"]["pi"]}, '
            f'{on}, {od}, {str(unit["affine"]).lower()}, {str(unit["prefixable"]).lower()}, '
            f'"{unit["category"]}", "{unit["since"]}"}},'
        )
    lines += [
        "};",
        "",
        "/// Unit aliases, in the engine's order.",
        "inline constexpr const char* kUnitAliases[][2] = {",
    ]
    for alias, name in aliases:
        lines.append(f'    {{"{alias}", "{name}"}},')
    lines += [
        "};",
        "",
        "/// The unit with this canonical name, or nullptr.",
        "inline const UnitDef* find_unit(const char* name) {",
        "    for (const UnitDef& unit : kUnits) {",
        "        if (std::strcmp(unit.name, name) == 0) return &unit;",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "/// The unit with this name or alias, or nullptr.",
        "inline const UnitDef* lookup_unit(const char* name) {",
        "    if (const UnitDef* unit = find_unit(name)) return unit;",
        "    for (const auto& alias : kUnitAliases) {",
        "        if (std::strcmp(alias[0], name) == 0) return find_unit(alias[1]);",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "}  // namespace client",
        "}  // namespace rssn",
        "",
        "#endif  // RSSN_CLIENT_UNITS_HPP",
        "",
    ]
    return "\n".join(lines)


def emit_cpp_constants(api: dict) -> str:
    lines = [
        f"// {BANNER}",
        "",
        "#ifndef RSSN_CLIENT_CONSTANTS_HPP",
        "#define RSSN_CLIENT_CONSTANTS_HPP",
        "",
        "#include <cmath>",
        "#include <cstring>",
        "",
        "namespace rssn {",
        "namespace client {",
        "",
        "/// A physical constant of the engine's table: the exact rational value",
        "/// `numer / denom * pi^pi`, its dimension text, its unit and its standard",
        "/// uncertainty (`nullptr` for an exact constant).",
        "struct ConstantDef {",
        "    const char* name;",
        "    const char* symbol;",
        "    const char* numer;",
        "    const char* denom;",
        "    int pi;",
        "    const char* dimension;",
        "    const char* unit;",
        "    bool exact;",
        "    const char* uncertainty;  // \"numer/denom\", or nullptr",
        "    const char* source;",
        "};",
        "",
        "/// Every constant of the engine's table, sorted by display name.",
        "inline constexpr ConstantDef kConstants[] = {",
    ]
    for constant in api["constants"]:
        uncertainty = "nullptr" if constant["uncertainty"] is None             else f'"{constant["uncertainty"]}"'
        lines.append(
            f'    {{"{constant["name"]}", "{constant["symbol"]}", "{constant["numer"]}", '
            f'"{constant["denom"]}", {constant["pi"]}, "{constant["dimension"]}", '
            f'"{constant["unit"]}", {str(constant["exact"]).lower()}, {uncertainty}, '
            f'"{constant["source"]}"}},'
        )
    lines += [
        "};",
        "",
        "/// The constant with this display name or symbol, or nullptr.",
        "inline const ConstantDef* lookup_constant(const char* name) {",
        "    for (const ConstantDef& constant : kConstants) {",
        "        if (std::strcmp(constant.name, name) == 0) return &constant;",
        "    }",
        "    for (const ConstantDef& constant : kConstants) {",
        "        if (std::strcmp(constant.symbol, name) == 0) return &constant;",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "/// The numeric value of a constant: `numer / denom * pi^pi`.",
        "inline double constant_value(const ConstantDef& constant) {",
        "    const double numer = std::strtod(constant.numer, nullptr);",
        "    const double denom = std::strtod(constant.denom, nullptr);",
        "    return numer / denom * std::pow(3.14159265358979323846, constant.pi);",
        "}",
        "",
        "}  // namespace client",
        "}  // namespace rssn",
        "",
        "#endif  // RSSN_CLIENT_CONSTANTS_HPP",
        "",
    ]
    return "\n".join(lines)


def emit_cpp_scenarios(api: dict) -> str:
    """`scenarios.hpp`: the simulation catalog, with the parameters each reads."""
    def summary(scenario: dict) -> str:
        parts = []
        for field, spec in scenario["params"].items():
            default = spec["default"]
            if default is None:
                parts.append(f"{field}:{spec['type']}")
            else:
                text = "true" if default is True else "false" if default is False \
                    else repr(default)
                parts.append(f"{field}:{spec['type']}={text}")
        return "; ".join(parts)

    lines = [
        f"// {BANNER}",
        "",
        "#ifndef RSSN_CLIENT_SCENARIOS_HPP",
        "#define RSSN_CLIENT_SCENARIOS_HPP",
        "",
        "#include <cstring>",
        "",
        "namespace rssn {",
        "namespace client {",
        "",
        "/// A simulation scenario: its name, the group it belongs to (`fixed` or",
        "/// `engine`) and the parameters its request type reads, as",
        "/// `field:type[=default]` separated by `;`. `Session::run_scenario()` takes",
        "/// the name and a JSON object of those parameters.",
        "struct ScenarioDef {",
        "    const char* name;",
        "    const char* group;",
        "    const char* params;",
        "};",
        "",
        "/// Every scenario of the engine's catalog, in catalog order.",
        "inline constexpr ScenarioDef kScenarios[] = {",
    ]
    for scenario in api["scenarios"]:
        lines.append(
            f'    {{"{scenario["name"]}", "{scenario["group"]}", "{summary(scenario)}"}},'
        )
    lines += [
        "};",
        "",
        "/// The scenario with this name, or nullptr.",
        "inline const ScenarioDef* lookup_scenario(const char* name) {",
        "    for (const ScenarioDef& scenario : kScenarios) {",
        "        if (std::strcmp(scenario.name, name) == 0) return &scenario;",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "}  // namespace client",
        "}  // namespace rssn",
        "",
        "#endif  // RSSN_CLIENT_SCENARIOS_HPP",
        "",
    ]
    return "\n".join(lines)


