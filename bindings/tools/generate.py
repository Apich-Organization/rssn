PY_HEADER = '''"""{banner}"""

from __future__ import annotations

from .session import default_session
from .term import Term

#: Operator name -> ``(min_arity, max_arity, ffi_reachable)``. ``max_arity`` is
#: ``None`` for a variadic operator. ``ffi_reachable`` is the manifest's
#: ``backend_support.ffi``, which is ``True`` for every operator: terms go
#: through ``apply``, values through ``Session.call_value``, and functions
#: through a host callback registered on the way.
OPS: dict[str, tuple[int, int | None, bool]] = {{
{ops_table}}}

#: Operator name -> Python identifier. They differ only for names that are
#: Python keywords (``and`` -> ``and_``).
NAMES: dict[str, str] = {{
{names_table}}}

#: Operators grouped by rule set, for discovery.
BY_RULE_SET: dict[str, tuple[str, ...]] = {{
{by_rule_set}}}

#: Operators grouped by manifest category (``numerical_matrix``, ``solve``, ...).
BY_CATEGORY: dict[str, tuple[str, ...]] = {{
{by_category}}}


def _apply(name: str, args: tuple, session) -> Term:
    """Resolve the session from the first term argument, else the default one."""
    if session is None:
        for arg in args:
            if isinstance(arg, Term):
                session = arg.session
                break
        else:
            session = default_session()
    return session.apply(name, *args)


def _call(name: str, args: tuple, session):
    """Resolve the session and call a higher-order operator through the value ABI.

    The value ABI is the one that can carry a host callback, so a callable in
    ``args`` becomes one, registered with the signature this operator declares.
    """
    if session is None:
        for arg in args:
            if isinstance(arg, Term):
                session = arg.session
                break
        else:
            session = default_session()
    return session.call_value(name, *args)

'''


def emit_python_ops(api: dict) -> str:
    ops = api["ops"]
    table = []
    names = []
    by_rule: dict[str, list[str]] = {}
    by_category: dict[str, list[str]] = {}
    for op in ops:
        name = op["name"]
        maximum = "None" if op["arity_max"] is None else op["arity_max"]
        table.append(f'    "{name}": ({op["arity_min"]}, {maximum}, {op["ffi"]}),')
        names.append(f'    "{name}": "{py_name(name)}",')
        by_rule.setdefault(op["rule_set"], []).append(py_name(name))
        by_category.setdefault(op["category"] or "uncategorised", []).append(py_name(name))

    def groups(source: dict[str, list[str]]) -> str:
        lines = []
        for key in sorted(source):
            entries = ", ".join(f'"{entry}"' for entry in sorted(source[key]))
            lines.append(f'    "{key}": ({entries}),')
        return "\n".join(lines)

    text = PY_HEADER.format(
        banner=BANNER,
        ops_table="\n".join(table),
        names_table="\n".join(names),
        by_rule_set=groups(by_rule),
        by_category=groups(by_category),
    )

    chunks = [text]
    for op in ops:
        chunks.append(_python_function(op))
    # Aliases: a second name for the same operator, as a thin forwarder.
    for op in ops:
        for alias in op["aliases"]:
            if alias in {entry["name"] for entry in ops}:
                continue
            chunks.append(
                f'\n{py_name(alias)} = {py_name(op["name"])}\n'
                f'"""Alias of :func:`{py_name(op["name"])}`."""\n'
            )
    chunks.append("\n\n__all__ = [\n" + "".join(
        f'    "{py_name(op["name"])}",\n' for op in ops
    ) + "]\n")
    return "".join(chunks)


def _python_function(op: dict) -> str:
    name = py_name(op["name"])
    minimum, maximum = op["arity_min"], op["arity_max"]
    # A higher-order operator can only be called through the value ABI, because
    # that is the one that carries a host callback.
    caller = "_call" if op["eval"] == "host_callback" else "_apply"
    doc = "\n".join(
        "    " + line for line in _doc_block([_clean_doc(op["doc"])], op, comment="#")
    )
    if maximum is None:
        return (
            f'\n\ndef {name}(*args, session=None):\n'
            f'    """\n{doc}\n    """\n'
            f'    return {caller}("{op["name"]}", args, session)\n'
        )
    params = ", ".join(f"a{index}" for index in range(maximum))
    passed = ", ".join(f"a{index}" for index in range(maximum))
    tuple_text = f"({passed},)" if maximum == 1 else f"({passed})"
    if maximum == 0:
        return (
            f'\n\ndef {name}(*, session=None):\n'
            f'    """\n{doc}\n    """\n'
            f'    return {caller}("{op["name"]}", (), session)\n'
        )
    return (
        f'\n\ndef {name}({params}, *, session=None):\n'
        f'    """\n{doc}\n    """\n'
        f'    return {caller}("{op["name"]}", {tuple_text}, session)\n'
    )


