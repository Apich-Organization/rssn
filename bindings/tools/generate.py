def emit_julia_constants(api: dict) -> str:
    lines = [
        f"# {BANNER}",
        "",
        '"""A physical constant: exact rational value, `pi` power, dimension text."""',
        "struct PhysicalConstant",
        "    name::String",
        "    symbol::String",
        "    numer::String",
        "    denom::String",
        "    pi::Int",
        "    dimension::String",
        "    unit::String",
        "    exact::Bool",
        "    uncertainty::Union{String, Nothing}",
        "    source::String",
        "end",
        "",
        '"""`value(c)` is `numer/denom * pi^pi` as a `Float64`."""',
        "function value(constant::PhysicalConstant)",
        "    return parse(Float64, constant.numer) / parse(Float64, constant.denom) *",
        "           pi ^ constant.pi",
        "end",
        "",
        "function Base.show(io::IO, constant::PhysicalConstant)",
        '    print(io, "PhysicalConstant(", constant.symbol, ", ", constant.dimension, ")")',
        "end",
        "",
        "#: Every constant, by its display name.",
        "const CONSTANTS = Dict{String, PhysicalConstant}(",
    ]
    for constant in api["constants"]:
        uncertainty = (
            "nothing" if constant["uncertainty"] is None else f'"{constant["uncertainty"]}"'
        )
        lines.append(
            f'    {json.dumps(constant["name"])} => PhysicalConstant('
            f'{json.dumps(constant["name"])}, {json.dumps(constant["symbol"])}, '
            f'"{constant["numer"]}", "{constant["denom"]}", {constant["pi"]}, '
            f'"{constant["dimension"]}", {json.dumps(constant["unit"])}, '
            f'{str(constant["exact"]).lower()}, {uncertainty}, '
            f'{json.dumps(constant["source"])}),'
        )
    lines += [
        ")",
        "",
        "#: Every symbol, mapped to its constant.",
        "const CONSTANT_BY_SYMBOL = Dict{String, PhysicalConstant}(",
        "    constant.symbol => constant for constant in values(CONSTANTS)",
        ")",
        "",
        '"""`constant(name)` looks a constant up by display name or symbol."""',
        "function constant(name::AbstractString)",
        "    haskey(CONSTANTS, name) && return CONSTANTS[name]",
        "    haskey(CONSTANT_BY_SYMBOL, name) && return CONSTANT_BY_SYMBOL[name]",
        '    throw(ArgumentError("unknown constant $name"))',
        "end",
        "",
    ]
    return "\n".join(lines)


def _jl_literal(value) -> str:
    """A Python value as a Julia literal (`None` is `nothing`, not `null`)."""
    if value is None:
        return "nothing"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return json.dumps(value)


def emit_julia_scenarios(api: dict) -> str:
    return "\n".join(
        [
            f"# {BANNER}",
            "",
            '"""Scenario names `run_scenario` accepts, in catalog order."""',
            "const SCENARIO_NAMES = [",
        ]
        + [f'    "{scenario["name"]}",' for scenario in api["scenarios"]]
        + [
            "]",
            "",
            "#: Scenario name => the parameters its request type reads.",
            "const SCENARIO_PARAMS = Dict{String, Vector{Tuple{String, String, Any}}}(",
        ]
        + [
            '    "{}" => [{}],'.format(
                scenario["name"],
                ", ".join(
                    f'("{field}", "{spec["type"]}", {_jl_literal(spec["default"])})'
                    for field, spec in scenario["params"].items()
                ),
            )
            for scenario in api["scenarios"]
        ]
        + [")", ""]
    )



#: Operator names that are also Base functions and are safe to extend, so that
#: `sin(x)` and `diff(f, x)` read naturally on a `Term`.
JL_BASE_EXTENSIONS = (
    "abs", "acos", "acosh", "acot", "acoth", "acsc", "acsch", "angle", "asec", "asech",
    "asin", "asinh", "atan", "atanh", "binomial", "ceil", "conj", "cos", "cosh", "cot",
    "coth", "csc", "csch", "diff", "exp", "factorial", "floor", "gcd", "invmod", "isqrt",
    "kron", "lcm", "log", "round", "sec", "sech", "sign", "sin", "sinc", "sinh", "sqrt",
    "sum", "tan", "tanh", "transpose",
)


def jl_base_names() -> set[str]:
    """The names `Base` exports, read from `api/julia_base_names.txt` when present."""
    path = BINDINGS / "api" / "julia_base_names.txt"
    if not path.exists():
        return set()
    return {line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()}


def jl_base_functions() -> set[str]:
    """The names `Base` exports *and* that are functions, from the stored scan."""
    path = BINDINGS / "api" / "julia_base_functions.txt"
    if not path.exists():
        return set()
    return {line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()}


def emit_julia_base_ext(api: dict) -> str:
    lines = [
        f"# {BANNER}",
        "#",
        "# `Term` methods on Base functions, so `sin(x)`, `sqrt(x)` and `diff(f, x)`",
        "# read naturally. A name that Base already exports is not re-exported by",
        "# RSSN (that would make `using RSSN` ambiguous), so this is how the common",
        "# mathematical operators reach unqualified call sites.",
        "",
    ]
    present = {op["name"] for op in api["ops"]}
    functions = jl_base_functions()
    for name in JL_BASE_EXTENSIONS:
        if name not in present or (functions and name not in functions):
            continue
        lines.append(
            f'Base.{name}(a::Term, rest...) = _apply("{name}", (a, rest...), nothing)'
        )
    return "\n".join(lines) + "\n"


def emit_julia_exports(api: dict) -> str:
    # A base-extension operator has no module-local function to export; the rest
    # are exported under their (possibly mangled) binding name.
    names = [jl_name(op["name"]) for op in api["ops"] if op["name"] not in JL_BASE_EXTENSIONS]
    names = sorted(set(names))
    lines = [
        f"# {BANNER}",
        "#",
        "# Every operator whose name `Base` does not already export. The rest stay",
        "# reachable as `RSSN.sin(x)` (and as `sin(x)` through `base_ext.jl`).",
        "",
        "export",
    ]
    width = 92
    row: list[str] = []
    for name in names:
        row.append(name)
        if sum(len(entry) + 2 for entry in row) > width:
            lines.append("    " + ", ".join(row[:-1]) + ",")
            row = [name]
    if row:
        lines.append("    " + ", ".join(row))
    return "\n".join(lines) + "\n"


