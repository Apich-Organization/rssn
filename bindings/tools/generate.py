def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    api = load_api()
    stale = []
    for relative, emitter in OUTPUTS.items():
        path = BINDINGS / relative
        text = emitter(api)
        if path.suffix == ".hpp":
            text = subprocess.run(
                [os.environ.get("CLANG_FORMAT", "clang-format"), "--style=LLVM",
                 f"--assume-filename={path.name}"],
                input=text, encoding="utf-8", stdout=subprocess.PIPE, check=True,
            ).stdout
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        newline = "\r\n" if path.exists() and b"\r\n" in path.read_bytes() else "\n"
        with path.open("w", encoding="utf-8", newline=newline) as output:
            output.write(text)
        print(f"wrote {path.relative_to(BINDINGS)} ({len(text.splitlines())} lines)")

    if args.check:
        if stale:
            print("error: stale generated files: " + ", ".join(stale), file=sys.stderr)
            return 1
        print("generated files are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
