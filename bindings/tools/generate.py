#!/usr/bin/env python3
"""Generate the language-specific tables and operator facades.

Input: `bindings/api/rssn_api.json` (see `extract_api.py`).
Output: files marked "generated" in `bindings/python`, `bindings/julia`,
`bindings/r` and `bindings/cpp`. Everything else in those trees is hand-written.

    python bindings/tools/generate.py
    python bindings/tools/generate.py --check   # exit 1 when a file is stale

The operator facade is one function per registered operator, so a caller never
has to spell an operator name as a string. Names that are keywords in a target
language are mangled (`and` -> `and_` in Python, `and_op` in C++) and the
original spelling stays reachable through `OPS` / `apply`.

Parameter names come from the operator's own documentation where it states its
signature (`` `diff(f, x)`: ... ``), so `rssn.diff(f = ..., x = ...)` reads as
the engine's own documentation does; the rest fall back to `a0`, `a1`, ... A
name that would collide with the host language's keywords, with the session
argument, or with another parameter of the same operator falls back too.
"""

