PY_HEADER = '''"""{banner}"""

from __future__ import annotations

from .session import default_session
from .term import Term

#: Operator name -> ``(min_arity, max_arity, ffi_reachable)``. ``max_arity`` is
#: ``None`` for a variadic operator. ``ffi_reachable`` is the manifest's
#: ``backend_support.ffi``, which is ``True`` for every operator: terms go
#: through ``apply``, values through ``Session.call_value``, and functions
#: through a host callback registered on the way.
OPS: dict[str, tuple[int, int | None, bool]] = {{
{ops_table}}}

#: Operator name -> Python identifier. They differ only for names that are
#: Python keywords (``and`` -> ``and_``).
NAMES: dict[str, str] = {{
{names_table}}}

#: Operators grouped by rule set, for discovery.
BY_RULE_SET: dict[str, tuple[str, ...]] = {{
{by_rule_set}}}

#: Operators grouped by manifest category (``numerical_matrix``, ``solve``, ...).
BY_CATEGORY: dict[str, tuple[str, ...]] = {{
{by_category}}}


def _apply(name: str, args: tuple, session) -> Term:
    """Resolve the session from the first term argument, else the default one."""
    if session is None:
        for arg in args:
            if isinstance(arg, Term):
                session = arg.session
                break
        else:
            session = default_session()
    return session.apply(name, *args)


def _call(name: str, args: tuple, session):
    """Resolve the session and call an operator through the value ABI.

    The value ABI is the one that can carry a host callback, so a callable in
    ``args`` becomes one, registered with the signature this operator declares.
    """
    if session is None:
        from .callback import Callback
        from .value import Value

        session = next((arg.session for arg in args if isinstance(arg, (Term, Value, Callback))), None)
        if session is None:
            session = default_session()
    return session.call_value(name, *args)

'''


def emit_python_ops(api: dict) -> str:
    ops = api["ops"]
    table = []
    names = []
    by_rule: dict[str, list[str]] = {}
    by_category: dict[str, list[str]] = {}
    for op in ops:
        name = op["name"]
        maximum = "None" if op["arity_max"] is None else op["arity_max"]
        table.append(f'    "{name}": ({op["arity_min"]}, {maximum}, {op["ffi"]}),')
        names.append(f'    "{name}": "{py_name(name)}",')
        by_rule.setdefault(op["rule_set"], []).append(py_name(name))
        by_category.setdefault(op["category"] or "uncategorised", []).append(py_name(name))

    def groups(source: dict[str, list[str]]) -> str:
        lines = []
        for key in sorted(source):
            entries = ", ".join(f'"{entry}"' for entry in sorted(source[key]))
            lines.append(f'    "{key}": ({entries}),')
        return "\n".join(lines)

    text = PY_HEADER.format(
        banner=BANNER,
        ops_table="\n".join(table),
        names_table="\n".join(names),
        by_rule_set=groups(by_rule),
        by_category=groups(by_category),
    )

    chunks = [text]
    for op in ops:
        chunks.append(_python_function(op))
    # Aliases: a second name for the same operator, as a thin forwarder.
    for op in ops:
        for alias in op["aliases"]:
            if alias in {entry["name"] for entry in ops}:
                continue
            chunks.append(
                f'\n{py_name(alias)} = {py_name(op["name"])}\n'
                f'"""Alias of :func:`{py_name(op["name"])}`."""\n'
            )
    chunks.append("\n\n__all__ = [\n" + "".join(
        f'    "{py_name(op["name"])}",\n' for op in ops
    ) + "]\n")
    return "".join(chunks)


def _python_function(op: dict) -> str:
    name = py_name(op["name"])
    minimum, maximum = op["arity_min"], op["arity_max"]
    # A higher-order operator can only be called through the value ABI, because
    # that is the one that carries a host callback.
    caller = "_call" if op["eval"] == "host_callback" else "_apply"
    checked = _checked_value(op)
    keyword_option = ", checked=False" if checked else ""
    if checked:
        caller = "(_call if checked else _apply)"
    doc = "\n".join(
        "    " + line for line in _doc_block([_clean_doc(op["doc"])], op, comment="#")
    )
    if maximum is None:
        return (
            f'\n\ndef {name}(*args, session=None{keyword_option}):\n'
            f'    """\n{doc}\n    """\n'
            f'    return {caller}("{op["name"]}", args, session)\n'
        )
    if maximum == 0:
        return (
            f'\n\ndef {name}(*, session=None{keyword_option}):\n'
            f'    """\n{doc}\n    """\n'
            f'    return {caller}("{op["name"]}", (), session)\n'
        )
    reserved = set(keyword.kwlist) | ({"checked"} if checked else set())
    names = param_names(op, "a", reserved)
    params = ", ".join(names)
    passed = ", ".join(names)
    tuple_text = f"({passed},)" if maximum == 1 else f"({passed})"
    return (
        f'\n\ndef {name}({params}, *, session=None{keyword_option}):\n'
        f'    """\n{doc}\n    """\n'
        f'    return {caller}("{op["name"]}", {tuple_text}, session)\n'
    )


def emit_python_units(api: dict) -> str:
    lines = [
        f'"""{BANNER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass",
        "from fractions import Fraction",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Unit:",
        '    """A unit of the engine\'s table, with an exact scale."""',
        "",
        "    name: str",
        "    display: str",
        "    dimension: str",
        "    numer: str",
        "    denom: str",
        "    pi: int",
        "    offset_numer: str | None",
        "    offset_denom: str | None",
        "    affine: bool",
        "    aliases: tuple[str, ...]",
        "    prefixable: bool",
        "    category: str",
        "    since: str",
        "",
        "    @property",
        "    def scale(self) -> Fraction:",
        '        """The exact scale as a fraction of the base unit (the `pi` power is separate)."""',
        "        return Fraction(int(self.numer), int(self.denom))",
        "",
        "    @property",
        "    def offset(self) -> Fraction | None:",
        '        """The exact affine offset, for `degC` and friends."""',
        "        if self.offset_numer is None:",
        "            return None",
        "        return Fraction(int(self.offset_numer), int(self.offset_denom))",
        "",
        "",
        "#: Every unit, by canonical name.",
        "UNITS: dict[str, Unit] = {",
    ]
    for unit in api["units"]:
        offset = unit["offset"]
        lines.append(
            f'    "{unit["name"]}": Unit('
            f'name="{unit["name"]}", display={unit["display"]!r}, '
            f'dimension="{unit["dimension"]}", '
            f'numer="{unit["scale"]["numer"]}", denom="{unit["scale"]["denom"]}", '
            f'pi={unit["scale"]["pi"]}, '
            f'offset_numer={"None" if offset is None else repr(offset["numer"])}, '
            f'offset_denom={"None" if offset is None else repr(offset["denom"])}, '
            f'affine={unit["affine"]}, aliases={tuple(unit["aliases"])!r}, '
            f'prefixable={unit["prefixable"]}, category="{unit["category"]}", '
            f'since="{unit["since"]}"),'
        )
    lines += [
        "}",
        "",
        "#: Every alias, canonical name included, mapped to its unit.",
        "BY_ALIAS: dict[str, Unit] = {}",
        "for _unit in UNITS.values():",
        "    BY_ALIAS[_unit.name] = _unit",
        "    for _alias in _unit.aliases:",
        "        BY_ALIAS.setdefault(_alias, _unit)",
        "del _unit, _alias",
        "",
        "",
        "def get(name: str) -> Unit:",
        '    """The unit with this name or alias."""',
        "    try:",
        "        return BY_ALIAS[name]",
        "    except KeyError:",
        '        raise KeyError(f"unknown unit {name!r}") from None',
        "",
        "",
        "def names() -> list[str]:",
        '    """Every canonical unit name, sorted."""',
        "    return sorted(UNITS)",
        "",
        "__all__ = [\"BY_ALIAS\", \"UNITS\", \"Unit\", \"get\", \"names\"]",
        "",
    ]
    return "\n".join(lines)


def emit_python_constants(api: dict) -> str:
    lines = [
        f'"""{BANNER}"""',
        "",
        "from __future__ import annotations",
        "",
        "import math",
        "from dataclasses import dataclass",
        "from fractions import Fraction",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Constant:",
        '    """A physical constant with its exact rational value and dimension."""',
        "",
        "    name: str",
        "    symbol: str",
        "    numer: str",
        "    denom: str",
        "    pi: int",
        "    dimension: str",
        "    unit: str",
        "    exact: bool",
        "    uncertainty: str | None",
        "    source: str",
        "",
        "    @property",
        "    def rational(self) -> Fraction:",
        '        """The exact value without the `pi` power."""',
        "        return Fraction(int(self.numer), int(self.denom))",
        "",
        "    @property",
        "    def uncertainty_value(self) -> float | None:",
        '        """The standard uncertainty as a float, for a measured constant."""',
        "        if self.uncertainty is None:",
        "            return None",
        "        numer, _, denom = self.uncertainty.partition(\"/\")",
        "        return int(numer) / int(denom)",
        "",
        "    def value(self) -> float:",
        '        """A float approximation of `rational * pi**pi`."""',
        "        return float(self.rational) * math.pi ** self.pi",
        "",
        "",
        "#: Every constant, by its display name.",
        "CONSTANTS: dict[str, Constant] = {",
    ]
    for constant in api["constants"]:
        uncertainty = "None" if constant["uncertainty"] is None else repr(constant["uncertainty"])
        lines.append(
            f'    {constant["name"]!r}: Constant('
            f'name={constant["name"]!r}, symbol={constant["symbol"]!r}, '
            f'numer="{constant["numer"]}", denom="{constant["denom"]}", pi={constant["pi"]}, '
            f'dimension="{constant["dimension"]}", unit={constant["unit"]!r}, '
            f'exact={constant["exact"]}, uncertainty={uncertainty}, '
            f'source={constant["source"]!r}),'
        )
    lines += [
        "}",
        "",
        "#: Every symbol, mapped to its constant.",
        "BY_SYMBOL: dict[str, Constant] = {constant.symbol: constant for constant in CONSTANTS.values()}",
        "",
        "",
        "def get(name: str) -> Constant:",
        '    """The constant with this display name or symbol."""',
        "    if name in CONSTANTS:",
        "        return CONSTANTS[name]",
        "    if name in BY_SYMBOL:",
        "        return BY_SYMBOL[name]",
        '    raise KeyError(f"unknown constant {name!r}")',
        "",
        "",
        "__all__ = [\"BY_SYMBOL\", \"CONSTANTS\", \"Constant\", \"get\"]",
        "",
    ]
    return "\n".join(lines)


